//! Explicit regeneration only; ordinary builds consume checked-in DTOs.
use std::{
    env, fs,
    io::Write,
    path::Path,
    process::{Command, Stdio},
};
use typify::{TypeSpace, TypeSpaceSettings};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let repo = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let schema_dir = repo.join("web/scripts/desktop-contracts/schemas");
    let mut paths = fs::read_dir(schema_dir)?
        .map(|entry| entry.map(|entry| entry.path()))
        .collect::<Result<Vec<_>, _>>()?;
    paths.sort();
    let mut code = String::from(
        "// Generated by typify 0.5.0; run npm run contracts:generate in web.\n// Structural DTOs only: semantics.rs is the validated boundary.\n",
    );
    for path in paths {
        if !path
            .file_name()
            .unwrap()
            .to_str()
            .unwrap()
            .ends_with(".schema.json")
        {
            continue;
        }
        let module = path
            .file_name()
            .unwrap()
            .to_str()
            .unwrap()
            .strip_suffix(".schema.json")
            .ok_or("Unexpected schema name")?
            .replace(['-', '.'], "_");
        let mut schema: schemars::schema::RootSchema = serde_json::from_slice(&fs::read(&path)?)?;
        schema.schema.metadata().title = Some("Dto".to_owned());
        let mut types = TypeSpace::new(&TypeSpaceSettings::default());
        types.add_root_schema(schema)?;
        let source = prettyplease::unparse(&syn::parse2(types.to_stream())?);
        code.push_str(&format!("pub(crate) mod {module} {{\n{source}\n}}\n"));
    }
    let formatted = prettyplease::unparse(&syn::parse_file(&code)?);
    let output = repo.join("rust/crates/pp-api-types/src/generated.rs");
    let bytes = format!(
        "// Generated by typify 0.5.0; run npm run contracts:generate in web.\n// Structural DTOs only: semantics.rs is the validated boundary.\n{formatted}"
    );
    let mut formatter = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()?;
    formatter
        .stdin
        .take()
        .ok_or("rustfmt stdin")?
        .write_all(bytes.as_bytes())?;
    let formatted = formatter.wait_with_output()?;
    if !formatted.status.success() {
        return Err("rustfmt failed".into());
    }
    let bytes = String::from_utf8(formatted.stdout)?;
    match env::args().nth(1).as_deref() {
        Some("--write") => fs::write(output, bytes)?,
        Some("--check") => {
            if fs::read_to_string(output)? != bytes {
                return Err("Rust DTO drift: run npm run contracts:generate".into());
            }
        }
        _ => return Err("Usage: generate-wire-dtos --write|--check".into()),
    }
    println!("PASS: typify DTO generation");
    Ok(())
}
