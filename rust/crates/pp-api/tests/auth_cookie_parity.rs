const HTTPS_ORIGIN: &str = "https://127.0.0.1:48921";
const LOGIN_LOOPBACK: &str = "pp_session=<token>; Max-Age=1209600; Path=/; HttpOnly; SameSite=Lax";
const LOGIN_HTTPS_NODE: &str =
    "pp_session=<token>; Max-Age=1209600; Path=/; HttpOnly; Secure; SameSite=Lax";
const LOGIN_HTTPS_RUST: &str =
    "pp_session=<token>; Max-Age=1209600; Path=/; HttpOnly; SameSite=Lax; Secure";
const CLEAR_NODE: &str =
    "pp_session=; Max-Age=0; Path=/; Expires=Thu, 01 Jan 1970 00:00:00 GMT; SameSite=Lax";
const CLEAR_LOOPBACK_RUST: &str = "pp_session=; Max-Age=0; Path=/; HttpOnly; SameSite=Lax";
const CLEAR_HTTPS_RUST: &str = "pp_session=; Max-Age=0; Path=/; HttpOnly; SameSite=Lax; Secure";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Fixture {
    generated: String,
    source: String,
    account: Account,
    cases: Vec<Case>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Account {
    email: String,
    password: String,
    display_name: String,
}
#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Case {
    id: String,
    transport: Transport,
    session_cookie_secure: bool,
    node: NodeCookie,
}
#[derive(Clone, Copy, Debug, Deserialize, PartialEq)]
enum Transport {
    #[serde(rename = "loopback")]
    Loopback,
    #[serde(rename = "https")]
    Https,
}
#[derive(Debug, Deserialize, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct NodeCookie {
    status: u16,
    set_cookie: Vec<String>,
}

fn fixture() -> Fixture {
    let fixture: Fixture = serde_json::from_str(include_str!(
        "../../../../fixtures/parity/auth-cookie/node.json"
    ))
    .unwrap();
    assert_eq!(
        fixture.generated,
        "@generated by fixtures/parity/auth-cookie/generate.mjs. Do not edit."
    );
    assert_eq!(fixture.source, "web/apps/server/src/routes/auth.ts");
    assert_eq!(
        fixture
            .cases
            .iter()
            .map(|case| case.id.as_str())
            .collect::<Vec<_>>(),
        [
            "login-loopback",
            "login-rejected-loopback",
            "logout-loopback",
            "logout-absent-loopback",
            "login-https",
            "login-rejected-https",
            "logout-https",
            "logout-absent-https",
        ]
    );
    for case in &fixture.cases {
        let secure = case.transport == Transport::Https;
        assert_eq!(case.session_cookie_secure, secure, "{}", case.id);
        let (status, cookies) = node_contract(&case.id);
        assert_eq!(case.node.status, status, "{}", case.id);
        assert_eq!(case.node.set_cookie, cookies, "{}", case.id);
    }
    fixture
}

fn node_contract(id: &str) -> (u16, Vec<String>) {
    let (status, cookies): (u16, &[&str]) = match id {
        "login-loopback" => (200, &[LOGIN_LOOPBACK]),
        "login-https" => (200, &[LOGIN_HTTPS_NODE]),
        "login-rejected-loopback" | "login-rejected-https" => (401, &[]),
        "logout-loopback" | "logout-absent-loopback" | "logout-https" | "logout-absent-https" => {
            (200, &[CLEAR_NODE])
        }
        _ => panic!("unknown cookie case {id}"),
    };
    (
        status,
        cookies.iter().map(|cookie| (*cookie).to_owned()).collect(),
    )
}

fn rust_difference(id: &str) -> Option<&'static str> {
    match id {
        "login-https" => Some(LOGIN_HTTPS_RUST),
        "logout-loopback" | "logout-absent-loopback" => Some(CLEAR_LOOPBACK_RUST),
        "logout-https" | "logout-absent-https" => Some(CLEAR_HTTPS_RUST),
        _ => None,
    }
}

fn compare(expected: &[String], actual: &[String]) -> Result<(), String> {
    if expected == actual {
        Ok(())
    } else {
        Err(format!("expected {expected:?}, received {actual:?}"))
    }
}

fn redact(header: &str) -> String {
    let rest = header
        .strip_prefix("pp_session=")
        .expect("pp_session cookie");
    let (value, suffix) = match rest.split_once(';') {
        Some((value, suffix)) => (value, format!(";{suffix}")),
        None => (rest, String::new()),
    };
    if value.is_empty() {
        return header.to_owned();
    }
    assert_eq!(value.len(), 64, "session token length");
    assert!(
        value
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase()),
        "session token shape"
    );
    let redacted = format!("pp_session=<token>{suffix}");
    assert!(
        !redacted.contains(value),
        "redaction left the session token"
    );
    redacted
}

fn issued_pair(header: &str) -> Option<String> {
    let pair = header.split(';').next()?;
    let value = pair.strip_prefix("pp_session=")?;
    (value.len() == 64
        && value
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase()))
    .then(|| pair.to_owned())
}

fn attribute_changes(header: &str) -> Vec<String> {
    let mut changed = vec![
        header.replace("SameSite=Lax", "SameSite=None"),
        header.replace("SameSite=Lax", "SameSite=Strict"),
        header.replace("Path=/", "Path=/auth"),
    ];
    if header.contains("Max-Age=1209600") {
        changed.push(header.replace("Max-Age=1209600", "Max-Age=60"));
    }
    if header.contains("Max-Age=0") {
        changed.push(header.replace("Max-Age=0", "Max-Age=1209600"));
    }
    if header.contains("Expires=Thu, 01 Jan 1970 00:00:00 GMT") {
        changed.push(header.replace(
            "Expires=Thu, 01 Jan 1970 00:00:00 GMT",
            "Expires=Thu, 01 Jan 2099 00:00:00 GMT",
        ));
    }
    if header.contains("; HttpOnly") {
        changed.push(header.replace("; HttpOnly", ""));
    } else {
        changed.push(header.replace("; SameSite=Lax", "; HttpOnly; SameSite=Lax"));
    }
    if header.contains("; Secure") {
        changed.push(header.replace("; Secure", ""));
    } else {
        changed.push(format!("{header}; Secure"));
    }
    changed
}

fn mutated_lists(cookies: &[String]) -> Vec<Vec<String>> {
    if cookies.is_empty() {
        return vec![vec![LOGIN_LOOPBACK.to_owned()]];
    }
    let mut lists = vec![vec![], vec![cookies[0].clone(), cookies[0].clone()]];
    for header in attribute_changes(&cookies[0]) {
        assert_ne!(header, cookies[0], "mutation did not change {header}");
        lists.push(vec![header]);
    }
    lists
}

fn reject_mutations(label: &str, cookies: &[String]) -> usize {
    compare(cookies, cookies).unwrap();
    let mut rejected = 0;
    for changed in mutated_lists(cookies) {
        assert!(
            compare(cookies, &changed).is_err(),
            "{label} accepted {changed:?}"
        );
        rejected += 1;
    }
    rejected
}

fn backend(owner: &WriterOwner) -> AuthBackend {
    let policy = AuthPolicy {
        registration: RegistrationPolicy::FirstAccountOnly,
        first_user: FirstUserTenant::NewUser,
        session_tenant: SessionTenantPolicy::SingleAccountDefault,
    };
    #[cfg(feature = "desktop_rebuild")]
    let client = owner.rebuild_auth_with_policy(policy, Default::default());
    #[cfg(not(feature = "desktop_rebuild"))]
    let client = owner.auth_with_policy(policy);
    client.unwrap().into()
}

struct Server {
    listener: String,
    configured: String,
    client: Client,
    owner: Option<WriterOwner>,
    task: tokio::task::JoinHandle<()>,
    shutdown: Option<tokio::sync::oneshot::Sender<()>>,
    directory: PathBuf,
}
impl Server {
    async fn start(transport: Transport) -> Self {
        let mut bytes = [0; 12];
        getrandom::fill(&mut bytes).unwrap();
        let directory =
            std::env::temp_dir().join(format!("pp-auth-cookie-rust-{}", hex::encode(bytes)));
        std::fs::create_dir(&directory).unwrap();
        let owner = WriterOwner::open(&directory, Limits::default()).unwrap().0;
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let address = listener.local_addr().unwrap();
        let listener_origin = format!("http://{address}");
        let (cookie_transport, configured) = match transport {
            Transport::Loopback => (CookieTransport::LoopbackHttp, listener_origin.clone()),
            Transport::Https => (CookieTransport::Secure, HTTPS_ORIGIN.to_owned()),
        };
        let router = auth_router(
            AuthHttpConfig::new(&configured, cookie_transport, false, None, false).unwrap(),
            backend(&owner),
            ProviderClient::new(None, None).unwrap(),
            ResetMailer::disabled(),
        );
        let (shutdown, receive) = tokio::sync::oneshot::channel();
        let task = tokio::spawn(async move {
            axum::serve(
                listener,
                router.into_make_service_with_connect_info::<SocketAddr>(),
            )
            .with_graceful_shutdown(async {
                let _ = receive.await;
            })
            .await
            .unwrap();
        });
        let client = Client::builder()
            .no_proxy()
            .redirect(reqwest::redirect::Policy::none())
            .timeout(Duration::from_secs(30))
            .build()
            .unwrap();
        Self {
            listener: listener_origin,
            configured,
            client,
            owner: Some(owner),
            task,
            shutdown: Some(shutdown),
            directory,
        }
    }
    async fn post(
        &self,
        path: &str,
        body: Option<Value>,
        cookie: Option<&str>,
    ) -> (NodeCookie, Option<String>) {
        let mut request = self.client.post(format!("{}{path}", self.listener));
        if self.configured.starts_with("https://") {
            request = request
                .header("Host", self.configured.trim_start_matches("https://"))
                .header("Origin", &self.configured);
        } else {
            request = request.header("Origin", &self.listener);
        }
        if let Some(body) = body {
            request = request.json(&body);
        }
        if let Some(cookie) = cookie {
            request = request.header("Cookie", cookie);
        }
        let response = request.send().await.unwrap();
        let raw: Vec<String> = response
            .headers()
            .get_all("set-cookie")
            .iter()
            .map(|header| header.to_str().unwrap().to_owned())
            .collect();
        let session = raw.iter().find_map(|header| issued_pair(header));
        (
            NodeCookie {
                status: response.status().as_u16(),
                set_cookie: raw.iter().map(|header| redact(header)).collect(),
            },
            session,
        )
    }
    async fn stop(mut self) {
        self.shutdown.take().unwrap().send(()).unwrap();
        (&mut self.task).await.unwrap();
        self.owner.take().unwrap().shutdown().unwrap();
        std::fs::remove_dir_all(&self.directory).unwrap();
    }
}
impl Drop for Server {
    fn drop(&mut self) {
        self.task.abort();
        if let Some(owner) = self.owner.take() {
            owner.shutdown().unwrap();
        }
        let _ = std::fs::remove_dir_all(&self.directory);
    }
}

fn account_body(account: &Account, password: &str) -> Value {
    json!({
        "email": account.email,
        "password": password,
        "display_name": account.display_name,
    })
}

async fn observe(case: &Case, account: &Account) -> NodeCookie {
    let server = Server::start(case.transport).await;
    let (registered, _) = server
        .post(
            "/auth/register",
            Some(account_body(account, &account.password)),
            None,
        )
        .await;
    assert_eq!(registered.status, 200, "{} setup", case.id);
    assert_eq!(registered.set_cookie.len(), 1, "{} setup cookie", case.id);
    let actual = match case.id.as_str() {
        "login-loopback" | "login-https" => {
            server
                .post(
                    "/auth/login",
                    Some(account_body(account, &account.password)),
                    None,
                )
                .await
                .0
        }
        "login-rejected-loopback" | "login-rejected-https" => {
            server
                .post(
                    "/auth/login",
                    Some(account_body(account, "wrong-password")),
                    None,
                )
                .await
                .0
        }
        "logout-loopback" | "logout-https" => {
            let (login, session) = server
                .post(
                    "/auth/login",
                    Some(account_body(account, &account.password)),
                    None,
                )
                .await;
            assert_eq!(login.status, 200, "{} login", case.id);
            assert_eq!(login.set_cookie.len(), 1, "{} login cookie", case.id);
            let session = session.expect("login issues a session cookie");
            server
                .post("/auth/logout", Some(json!({})), Some(&session))
                .await
                .0
        }
        "logout-absent-loopback" | "logout-absent-https" => {
            server.post("/auth/logout", Some(json!({})), None).await.0
        }
        _ => panic!("unknown cookie case {}", case.id),
    };
    server.stop().await;
    actual
}

#[tokio::test]
async fn node_cookie_fixture_is_current() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let node = std::env::var_os("PP_SCHEMA_PARITY_NODE")
        .or_else(|| std::env::var_os("PP_TEST_NODE"))
        .unwrap_or_else(|| "node".into());
    let generator = root.join("fixtures/parity/auth-cookie/generate.mjs");
    let output = Command::new(&node)
        .arg(&generator)
        .arg("--check")
        .current_dir(&root)
        .output()
        .await
        .unwrap_or_else(|error| {
            panic!(
                "Cannot run {node:?} {generator:?} --check: {error}. Install Node 22 and web dependencies. Set PP_SCHEMA_PARITY_NODE or PP_TEST_NODE to select Node."
            )
        });
    assert!(
        output.status.success(),
        "Auth cookie fixture freshness check failed with {}. Install Node 22 and web dependencies. If node.json is out of date, regenerate it with {node:?} {generator:?}.\nstdout:\n{}\nstderr:\n{}",
        output.status,
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr),
    );
}

#[test]
fn comparator_rejects_attribute_and_clearing_mutations() {
    let fixture = fixture();
    let mut rejected = 0;
    for case in &fixture.cases {
        rejected += reject_mutations(&case.id, &case.node.set_cookie);
        if let Some(header) = rust_difference(&case.id) {
            assert!(
                compare(&case.node.set_cookie, &[header.to_owned()]).is_err(),
                "{} Node and Rust literals must stay distinct",
                case.id
            );
            rejected += reject_mutations(&format!("{} rust", case.id), &[header.to_owned()]);
        }
    }
    assert_eq!(rejected, 94);
    println!("rejected {rejected} cookie attribute and clearing mutations");
}

#[tokio::test]
async fn login_and_logout_cookies_match_node_literals() {
    let fixture = fixture();
    let mut matched = 0;
    let mut differences = 0;
    for case in &fixture.cases {
        let actual = observe(case, &fixture.account).await;
        assert_eq!(actual.status, case.node.status, "{}", case.id);
        if let Some(header) = rust_difference(&case.id) {
            assert!(
                compare(&case.node.set_cookie, &actual.set_cookie).is_err(),
                "{} must remain an unnormalized literal difference. Node={:?} Rust={:?}",
                case.id,
                case.node.set_cookie,
                actual.set_cookie
            );
            compare(&[header.to_owned()], &actual.set_cookie)
                .unwrap_or_else(|error| panic!("{} Rust cookie literal: {error}", case.id));
            differences += 1;
        } else {
            compare(&case.node.set_cookie, &actual.set_cookie)
                .unwrap_or_else(|error| panic!("{} Node cookie literal: {error}", case.id));
            matched += 1;
        }
        println!(
            "{}: status {} and literal Set-Cookie checked",
            case.id, actual.status
        );
    }
    assert_eq!((matched, differences), (3, 5));
}
