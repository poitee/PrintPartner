use pp_api::auth::{AuthHttpConfig, CookieTransport, ProviderClient, ResetMailer, auth_router};
use pp_storage::{
    Limits, WriterOwner,
    auth::{AuthPolicy, FirstUserTenant, RegistrationPolicy, SessionTenantPolicy},
};
use reqwest::{Client, Response};
use serde::Deserialize;
use serde_json::{Value, json};
use std::{net::SocketAddr, path::PathBuf, time::Duration};

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Fixture {
    generated: String,
    source: String,
    configuration: Value,
    account: Value,
    cases: Vec<Case>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Case {
    id: String,
    registration_open: bool,
    seed_account: bool,
    request: WireRequest,
    node: PublicResponse,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct WireRequest {
    path: String,
    body: String,
}

#[derive(Clone, Debug, Deserialize, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct PublicResponse {
    status: u16,
    body: Value,
    set_cookie: Vec<String>,
}

fn fixture() -> Fixture {
    let fixture: Fixture = serde_json::from_str(include_str!(
        "../../../../fixtures/parity/auth-login/node.json"
    ))
    .unwrap();
    assert_eq!(
        fixture.generated,
        "@generated by fixtures/parity/auth-login/generate.mjs. Do not edit."
    );
    assert_eq!(fixture.source, "web/apps/server/src/routes/auth.ts");
    assert_eq!(
        fixture.configuration,
        json!({"deployMode":"self-host", "singleUserAuth":true, "multiUser":false, "sessionCookieSecure":false})
    );
    assert_eq!(
        fixture
            .cases
            .iter()
            .map(|case| case.id.as_str())
            .collect::<Vec<_>>(),
        [
            "unknown-account",
            "bad-password",
            "empty-object",
            "missing-email",
            "missing-password",
            "email-wrong-type",
            "password-wrong-type",
            "array-body",
            "null-body",
            "malformed-json",
            "registration-closed",
            "administrator-exists",
            "registration-invalid-email",
            "registration-short-password",
        ]
    );
    fixture
}

fn compare(expected: &PublicResponse, actual: &PublicResponse) -> Result<(), String> {
    if expected == actual {
        Ok(())
    } else {
        Err(format!("expected {expected:?}, received {actual:?}"))
    }
}

fn rust_difference(id: &str) -> Option<PublicResponse> {
    match id {
        "array-body" | "null-body" | "malformed-json" => Some(PublicResponse {
            status: 400,
            body: json!({"detail":"Invalid JSON body"}),
            set_cookie: vec![],
        }),
        _ => None,
    }
}

async fn observe(response: Response) -> PublicResponse {
    PublicResponse {
        status: response.status().as_u16(),
        set_cookie: response
            .headers()
            .get_all("set-cookie")
            .iter()
            .map(|header| header.to_str().unwrap().to_owned())
            .collect(),
        body: response.json().await.unwrap(),
    }
}

struct Directory(PathBuf);
impl Directory {
    fn new() -> Self {
        let mut bytes = [0; 12];
        getrandom::fill(&mut bytes).unwrap();
        let path = std::env::temp_dir().join(format!("pp-auth-login-rust-{}", hex::encode(bytes)));
        std::fs::create_dir(&path).unwrap();
        Self(path)
    }
}
impl Drop for Directory {
    fn drop(&mut self) {
        std::fs::remove_dir_all(&self.0).unwrap();
    }
}

#[test]
fn directory_cleanup_removes_only_its_own_directory() {
    let directory = Directory::new();
    let path = directory.0.clone();
    std::fs::write(path.join("disposable.txt"), "owned data").unwrap();
    let sibling = Directory::new();
    let sibling_file = sibling.0.join("keep.txt");
    std::fs::write(&sibling_file, "sibling data").unwrap();

    drop(directory);

    assert!(!path.exists());
    assert_eq!(
        std::fs::read_to_string(sibling_file).unwrap(),
        "sibling data"
    );
}

#[test]
fn directory_cleanup_failure_preserves_original_panic() {
    let directory = Directory::new();
    std::fs::remove_dir(&directory.0).unwrap();

    let result = std::panic::catch_unwind(move || {
        let _directory = directory;
        panic!("original auth parity assertion");
    });

    let panic = result.unwrap_err();
    assert_eq!(
        panic.downcast_ref::<&str>(),
        Some(&"original auth parity assertion")
    );
}

async fn run_case(case: &Case, account: &Value) -> PublicResponse {
    let directory = Directory::new();
    let owner = WriterOwner::open(&directory.0, Limits::default())
        .unwrap()
        .0;
    let auth = owner
        .auth_with_policy(AuthPolicy {
            registration: if case.registration_open {
                RegistrationPolicy::FirstAccountOnly
            } else {
                RegistrationPolicy::Closed
            },
            first_user: FirstUserTenant::NewUser,
            session_tenant: SessionTenantPolicy::SingleAccountDefault,
        })
        .unwrap();
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let origin = format!("http://{}", listener.local_addr().unwrap());
    let router = auth_router(
        AuthHttpConfig::new(&origin, CookieTransport::LoopbackHttp, false, None, false).unwrap(),
        auth,
        ProviderClient::new(None, None).unwrap(),
        ResetMailer::disabled(),
    );
    let (shutdown, receive) = tokio::sync::oneshot::channel();
    let task = tokio::spawn(async move {
        axum::serve(
            listener,
            router.into_make_service_with_connect_info::<SocketAddr>(),
        )
        .with_graceful_shutdown(async {
            let _ = receive.await;
        })
        .await
        .unwrap();
    });
    let client = Client::builder()
        .no_proxy()
        .redirect(reqwest::redirect::Policy::none())
        .timeout(Duration::from_secs(30))
        .build()
        .unwrap();
    let send = |path: &str, body: String| {
        client
            .post(format!("{origin}{path}"))
            .header("Origin", &origin)
            .header("Content-Type", "application/json")
            .body(body)
            .send()
    };
    let setup = if case.seed_account {
        let registered = observe(send("/auth/register", account.to_string()).await.unwrap()).await;
        let login = observe(send("/auth/login", account.to_string()).await.unwrap()).await;
        Some((registered, login))
    } else {
        None
    };
    let actual = observe(
        send(&case.request.path, case.request.body.clone())
            .await
            .unwrap(),
    )
    .await;
    shutdown.send(()).unwrap();
    task.await.unwrap();
    owner.shutdown().unwrap();
    if let Some((registered, login)) = setup {
        assert_eq!(registered.status, 200, "{} setup registration", case.id);
        assert_eq!(login.status, 200, "{} positive login control", case.id);
        assert_eq!(registered.body, login.body);
        assert_eq!(login.set_cookie.len(), 1);
        let token = login.set_cookie[0]
            .strip_prefix("pp_session=")
            .unwrap()
            .strip_suffix("; Max-Age=1209600; Path=/; HttpOnly; SameSite=Lax")
            .unwrap();
        assert!(!token.is_empty());
    }
    actual
}

#[tokio::test]
async fn registered_node_failures_match_rust_over_loopback() {
    let fixture = fixture();
    let mut matched = 0;
    let mut differences = 0;
    for case in &fixture.cases {
        let actual = run_case(case, &fixture.account).await;
        if let Some(expected) = rust_difference(&case.id) {
            assert!(
                compare(&case.node, &actual).is_err(),
                "{} must remain an explicit difference",
                case.id
            );
            compare(&expected, &actual)
                .unwrap_or_else(|error| panic!("{} Rust contract: {error}", case.id));
            differences += 1;
        } else {
            compare(&case.node, &actual)
                .unwrap_or_else(|error| panic!("{} Node parity: {error}", case.id));
            matched += 1;
        }
        println!(
            "{}: status {}, complete JSON and Set-Cookie checked",
            case.id, actual.status
        );
    }
    assert_eq!((matched, differences), (11, 3));
}

#[test]
fn comparator_rejects_status_body_and_cookie_mutations() {
    let fixture = fixture();
    let mut rejected = 0;
    for case in fixture.cases {
        for expected in std::iter::once(case.node).chain(rust_difference(&case.id)) {
            compare(&expected, &expected).unwrap();
            let mut changed = expected.clone();
            changed.status += 1;
            assert!(
                compare(&expected, &changed).is_err(),
                "{} status mutation",
                case.id
            );
            rejected += 1;
            for key in expected.body.as_object().unwrap().keys() {
                let mut changed = expected.clone();
                changed.body[key] = json!("mutated");
                assert!(
                    compare(&expected, &changed).is_err(),
                    "{} changed {key}",
                    case.id
                );
                let mut changed = expected.clone();
                changed.body.as_object_mut().unwrap().remove(key);
                assert!(
                    compare(&expected, &changed).is_err(),
                    "{} removed {key}",
                    case.id
                );
                rejected += 2;
            }
            let mut changed = expected.clone();
            changed.body["unexpected"] = json!(true);
            assert!(
                compare(&expected, &changed).is_err(),
                "{} added body field",
                case.id
            );
            let mut changed = expected.clone();
            changed
                .set_cookie
                .push("pp_session=unexpected; Path=/; HttpOnly".into());
            assert!(
                compare(&expected, &changed).is_err(),
                "{} unexpected cookie",
                case.id
            );
            rejected += 2;
        }
    }
    assert_eq!(rejected, 95);
    println!("rejected {rejected} status, JSON field, and cookie mutations");
}
