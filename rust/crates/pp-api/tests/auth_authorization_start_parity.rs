type Multimap = BTreeMap<String, Vec<String>>;
type Attributes = BTreeMap<String, Option<String>>;

#[derive(Clone, Copy, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
enum Provider {
    Github,
    Discord,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Fixture {
    generated: String,
    source: String,
    cases: Vec<Case>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Case {
    id: String,
    provider: Provider,
    path: String,
    callback: String,
    enabled: bool,
    secure: bool,
    origin: String,
    client_id: String,
    node: Observation,
}
#[derive(Clone, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
struct Observation {
    status: u16,
    redirect: Option<Redirect>,
    cookies: Vec<Cookie>,
    body: Value,
}
#[derive(Clone, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
struct Redirect {
    origin: String,
    path: String,
    parameters: Multimap,
}
#[derive(Clone, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
struct Cookie {
    name: String,
    value: String,
    attributes: Attributes,
}

fn fixture() -> Fixture {
    let fixture: Fixture = serde_json::from_str(include_str!(
        "../../../../fixtures/parity/auth-authorization-start/node.json"
    ))
    .expect("typed auth start fixture");
    assert_eq!(fixture.cases.len(), 8);
    assert_eq!(
        fixture.generated,
        "@generated by fixtures/parity/auth-authorization-start/generate.mjs. Do not edit."
    );
    assert_eq!(fixture.source, "web/apps/server/src/routes/auth.ts");
    let mut ids = HashSet::new();
    let mut dimensions = HashSet::new();
    for case in &fixture.cases {
        assert!(ids.insert(&case.id));
        assert!(dimensions.insert((case.provider == Provider::Github, case.enabled, case.secure)));
        let (path, callback, origin, authorize, scope) = match case.provider {
            Provider::Github => (
                "/auth/github",
                "/auth/callback",
                "https://github.com",
                "/login/oauth/authorize",
                "read:user user:email",
            ),
            Provider::Discord => (
                "/auth/discord",
                "/auth/discord/callback",
                "https://discord.com",
                "/api/oauth2/authorize",
                "identify email",
            ),
        };
        assert_eq!(case.path, path);
        assert_eq!(case.callback, callback);
        assert_eq!(
            case.client_id,
            match case.provider {
                Provider::Github => "fixture github+id/&=é",
                Provider::Discord => "fixture discord+id/&=é",
            }
        );
        assert_eq!(
            case.origin,
            if case.secure {
                "https://127.0.0.1:48885"
            } else {
                "http://127.0.0.1:48884"
            }
        );
        if case.enabled {
            let mut parameters = BTreeMap::from([
                ("client_id".into(), vec![case.client_id.clone()]),
                (
                    "redirect_uri".into(),
                    vec![format!("{}{callback}", case.origin)],
                ),
                ("scope".into(), vec![scope.into()]),
                ("state".into(), vec!["<state>".into()]),
            ]);
            if case.provider == Provider::Discord {
                parameters.insert("response_type".into(), vec!["code".into()]);
            }
            let mut attributes = BTreeMap::from([
                ("max-age".into(), Some("600".into())),
                ("path".into(), Some("/".into())),
                ("httponly".into(), None),
                ("samesite".into(), Some("Lax".into())),
            ]);
            if case.secure {
                attributes.insert("secure".into(), None);
            }
            let literal = Observation {
                status: 302,
                redirect: Some(Redirect {
                    origin: origin.into(),
                    path: authorize.into(),
                    parameters,
                }),
                cookies: vec![Cookie {
                    name: "oauth_state".into(),
                    value: "<state>".into(),
                    attributes,
                }],
                body: json!(""),
            };
            assert!(case.node == literal, "{} Node contract changed", case.id);
        } else {
            let detail = match case.provider {
                Provider::Github => {
                    "GitHub OAuth not configured. Set GITHUB_CLIENT_ID, GITHUB_CLIENT_SECRET, GITHUB_CALLBACK_URL."
                }
                Provider::Discord => "Discord OAuth not configured",
            };
            assert!(
                case.node
                    == Observation {
                        status: 501,
                        redirect: None,
                        cookies: vec![],
                        body: json!({"detail": detail}),
                    },
                "{} Node disabled contract changed",
                case.id
            );
        }
    }
    fixture
}

fn expected_rust(case: &Case) -> Observation {
    let mut expected = case.node.clone();
    if case.enabled {
        // Rust binds a separate browser secret. Node sends the state itself as its cookie.
        expected.cookies[0].value = "<browser-binding>".into();
        if case.provider == Provider::Github {
            let parameters = &mut expected.redirect.as_mut().unwrap().parameters;
            parameters.insert("code_challenge".into(), vec!["<pkce-s256>".into()]);
            parameters.insert("code_challenge_method".into(), vec!["S256".into()]);
        }
    } else {
        // The public Rust router uses one provider-neutral refusal body.
        expected.body = json!({"detail": "OAuth not configured"});
    }
    expected
}

struct Server {
    origin: String,
    client: Client,
    owner: WriterOwner,
    task: tokio::task::JoinHandle<()>,
    shutdown: tokio::sync::oneshot::Sender<()>,
    directory: PathBuf,
}
impl Server {
    async fn start(case: &Case) -> Self {
        let mut suffix = [0; 12];
        getrandom::fill(&mut suffix).unwrap();
        let directory =
            std::env::temp_dir().join(format!("pp-auth-start-rust-{}", hex::encode(suffix)));
        let owner = WriterOwner::open(&directory, Limits::default()).unwrap().0;
        let credentials = || {
            OAuthCredentials::new(case.client_id.clone(), Secret::new("fixture-secret".into()))
                .unwrap()
        };
        let providers = ProviderClient::new(
            (case.enabled && case.provider == Provider::Github).then(credentials),
            (case.enabled && case.provider == Provider::Discord).then(credentials),
        )
        .unwrap();
        let router = auth_router(
            AuthHttpConfig::new(
                &case.origin,
                if case.secure {
                    CookieTransport::Secure
                } else {
                    CookieTransport::LoopbackHttp
                },
                true,
                None,
                false,
            )
            .unwrap(),
            owner.auth(FirstUserTenant::NewUser),
            providers,
            ResetMailer::disabled(),
        );
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let origin = format!("http://{}", listener.local_addr().unwrap());
        let (shutdown, rx) = tokio::sync::oneshot::channel();
        let task = tokio::spawn(async move {
            axum::serve(
                listener,
                router.into_make_service_with_connect_info::<SocketAddr>(),
            )
            .with_graceful_shutdown(async {
                let _ = rx.await;
            })
            .await
            .unwrap();
        });
        let client = Client::builder()
            .redirect(reqwest::redirect::Policy::none())
            .no_proxy()
            .timeout(Duration::from_secs(10))
            .build()
            .unwrap();
        Self {
            origin,
            client,
            owner,
            task,
            shutdown,
            directory,
        }
    }
    async fn request(&self, case: &Case) -> Response {
        let host = case.origin.split_once("://").unwrap().1;
        self.client
            .get(format!("{}{}", self.origin, case.path))
            .header("Host", host)
            .send()
            .await
            .expect("loopback start response")
    }
    async fn close(self) {
        self.shutdown.send(()).unwrap();
        self.task.await.unwrap();
        self.owner.shutdown().unwrap();
        std::fs::remove_dir_all(self.directory).unwrap();
    }
}

fn generated(value: &str, seen: &mut HashSet<String>) {
    assert!(value.len() == 43, "generated value must encode 32 bytes");
    let decoded = URL_SAFE_NO_PAD
        .decode(value)
        .expect("base64url generated value");
    assert!(
        decoded.len() == 32 && URL_SAFE_NO_PAD.encode(decoded) == value,
        "canonical generated value"
    );
    assert!(
        seen.insert(value.into()),
        "generated values must be independent and fresh"
    );
}

async fn observe(response: Response, seen: &mut HashSet<String>) -> Observation {
    let status = response.status().as_u16();
    let mut cookies = Vec::new();
    for header in response.headers().get_all("set-cookie") {
        let mut parts = header.to_str().unwrap().split(';').map(str::trim);
        let (name, value) = parts.next().unwrap().split_once('=').unwrap();
        let mut attributes = BTreeMap::new();
        for part in parts {
            let (key, value) = part
                .split_once('=')
                .map_or((part, None), |(k, v)| (k, Some(v.into())));
            assert!(
                attributes.insert(key.to_ascii_lowercase(), value).is_none(),
                "duplicate cookie attribute"
            );
        }
        cookies.push(Cookie {
            name: name.into(),
            value: value.into(),
            attributes,
        });
    }
    assert!(
        response.headers().get_all("location").iter().count() <= 1,
        "at most one redirect required"
    );
    let redirect = response.headers().get("location").map(|location| {
        let url = Url::parse(location.to_str().unwrap()).expect("authorization URL");
        assert!(
            url.username().is_empty() && url.password().is_none() && url.fragment().is_none(),
            "unexpected URL component"
        );
        let mut parameters: Multimap = BTreeMap::new();
        for (key, value) in url.query_pairs() {
            parameters.entry(key.into()).or_default().push(value.into());
        }
        let states = parameters
            .get_mut("state")
            .expect("redirect state required");
        assert!(states.len() == 1, "exactly one state required");
        generated(&states[0], seen);
        assert!(
            cookies.len() == 1 && cookies[0].name == "oauth_state",
            "browser binding cookie required"
        );
        generated(&cookies[0].value, seen);
        // State and browser cookie enter the same set, so equality fails before normalization.
        states[0] = "<state>".into();
        cookies[0].value = "<browser-binding>".into();
        if let Some(challenges) = parameters.get_mut("code_challenge") {
            assert!(challenges.len() == 1, "exactly one PKCE challenge required");
            generated(&challenges[0], seen);
            challenges[0] = "<pkce-s256>".into();
        }
        Redirect {
            origin: url.origin().ascii_serialization(),
            path: url.path().into(),
            parameters,
        }
    });
    let text = response.text().await.unwrap();
    let body = if status == 302 {
        json!(text)
    } else {
        serde_json::from_str(&text).expect("refusal JSON")
    };
    Observation {
        status,
        redirect,
        cookies,
        body,
    }
}

fn matches_contract(case: &Case, observed: &Observation) -> bool {
    *observed == expected_rust(case)
}

#[tokio::test]
async fn authorization_start_matches_node_with_explicit_security_corrections() {
    let mut seen = HashSet::new();
    for case in fixture().cases {
        let server = Server::start(&case).await;
        for _ in 0..2 {
            let observed = observe(server.request(&case).await, &mut seen).await;
            assert!(
                matches_contract(&case, &observed),
                "{} Rust contract changed",
                case.id
            );
        }
        server.close().await;
    }
    assert_eq!(seen.len(), 20);
}

#[tokio::test]
async fn enabled_authorization_start_rejects_invalid_host() {
    let mut seen = HashSet::new();
    for case in fixture().cases.into_iter().filter(|case| case.enabled) {
        let server = Server::start(&case).await;
        let response = server
            .client
            .get(format!("{}{}", server.origin, case.path))
            .header("Host", "invalid.example")
            .send()
            .await
            .expect("loopback invalid host response");
        assert_eq!(response.status().as_u16(), 403, "{}", case.id);
        assert!(!response.headers().contains_key("location"), "{}", case.id);
        assert!(
            !response.headers().contains_key("set-cookie"),
            "{}",
            case.id
        );
        assert!(
            response.json::<Value>().await.unwrap() == json!({"detail": "Invalid request host"}),
            "{} invalid host refusal body changed",
            case.id
        );

        let control = observe(server.request(&case).await, &mut seen).await;
        assert_eq!(control.status, 302, "{}", case.id);
        assert!(matches_contract(&case, &control), "{}", case.id);
        server.close().await;
    }
}

#[tokio::test]
async fn contract_comparator_detects_mutated_authorization_start_observations() {
    let mut seen = HashSet::new();
    for case in fixture().cases {
        let server = Server::start(&case).await;
        let observed = observe(server.request(&case).await, &mut seen).await;
        assert!(matches_contract(&case, &observed));
        if case.enabled {
            let mut changed_callback = observed.clone();
            changed_callback
                .redirect
                .as_mut()
                .unwrap()
                .parameters
                .insert(
                    "redirect_uri".into(),
                    vec![format!("{}/wrong-callback", case.origin)],
                );
            assert!(
                !matches_contract(&case, &changed_callback),
                "changed callback must fail"
            );
            let mut missing_binding = observed.clone();
            missing_binding.cookies.clear();
            assert!(
                !matches_contract(&case, &missing_binding),
                "missing browser binding must fail"
            );
            let mut extra_parameter = observed.clone();
            extra_parameter
                .redirect
                .as_mut()
                .unwrap()
                .parameters
                .insert("unreviewed".into(), vec!["value".into()]);
            assert!(
                !matches_contract(&case, &extra_parameter),
                "extra parameters must fail"
            );
            let mut duplicate_parameter = observed;
            duplicate_parameter
                .redirect
                .as_mut()
                .unwrap()
                .parameters
                .get_mut("scope")
                .unwrap()
                .push("extra".into());
            assert!(
                !matches_contract(&case, &duplicate_parameter),
                "duplicate parameters must fail"
            );
        } else {
            let mut disabled_redirect = observed;
            disabled_redirect.status = 302;
            disabled_redirect.redirect = Some(Redirect {
                origin: "https://github.com".into(),
                path: "/login/oauth/authorize".into(),
                parameters: BTreeMap::new(),
            });
            assert!(
                !matches_contract(&case, &disabled_redirect),
                "disabled provider redirect must fail"
            );
        }
        server.close().await;
    }
}

