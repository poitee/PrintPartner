impl Kind {
    fn label(self) -> &'static str {
        match self {
            Self::MissingState => "missing-state",
            Self::ChangedState => "changed-state",
            Self::Denied => "denied",
            Self::Allow => "allow",
            Self::Replay => "replay",
        }
    }
    fn code(self) -> Option<&'static str> {
        match self {
            Self::Denied => Some("deny"),
            Self::Allow | Self::MissingState | Self::ChangedState => Some("allow"),
            Self::Replay => None,
        }
    }
}

fn flag_map(pairs: &[(&str, Option<&str>)]) -> Attributes {
    pairs
        .iter()
        .map(|(key, value)| ((*key).to_owned(), value.map(str::to_owned)))
        .collect()
}

fn session_attributes() -> Attributes {
    flag_map(&[
        ("httponly", None),
        ("max-age", Some("1209600")),
        ("path", Some("/")),
        ("samesite", Some("Lax")),
    ])
}

fn node_clear() -> Cookie {
    Cookie {
        name: "oauth_state".into(),
        value: String::new(),
        attributes: flag_map(&[
            ("expires", Some("Thu, 01 Jan 1970 00:00:00 GMT")),
            ("max-age", Some("0")),
            ("path", Some("/")),
            ("samesite", Some("Lax")),
        ]),
    }
}

fn rust_clear() -> Cookie {
    Cookie {
        name: "oauth_state".into(),
        value: String::new(),
        attributes: flag_map(&[
            ("httponly", None),
            ("max-age", Some("0")),
            ("path", Some("/")),
            ("samesite", Some("Lax")),
        ]),
    }
}

fn canonical(value: &str, seen: &mut HashSet<String>) {
    let decoded = URL_SAFE_NO_PAD
        .decode(value)
        .expect("base64url generated value");
    assert!(
        value.len() == 43 && decoded.len() == 32 && URL_SAFE_NO_PAD.encode(decoded) == value,
        "generated value is not canonical unpadded base64url for 32 bytes"
    );
    assert!(
        seen.insert(value.to_owned()),
        "generated oauth value was reused"
    );
}

fn s256(verifier: &str) -> String {
    URL_SAFE_NO_PAD.encode(Sha256::digest(verifier.as_bytes()))
}

async fn fake_request(
    State(fake): State<Fake>,
    method: Method,
    uri: Uri,
    headers: HeaderMap,
    bytes: Bytes,
) -> axum::response::Response {
    let content_type = headers
        .get("content-type")
        .and_then(|value| value.to_str().ok())
        .unwrap_or("")
        .to_owned();
    let authorization = headers
        .get("authorization")
        .and_then(|value| value.to_str().ok())
        .unwrap_or("")
        .to_owned();
    let fields = if content_type.contains("application/x-www-form-urlencoded") {
        Url::parse(&format!(
            "http://fixture/?{}",
            String::from_utf8_lossy(&bytes)
        ))
        .unwrap()
        .query_pairs()
        .map(|(key, value)| (key.into_owned(), value.into_owned()))
        .collect()
    } else if bytes.is_empty() {
        BTreeMap::new()
    } else {
        serde_json::from_slice::<Value>(&bytes)
            .unwrap()
            .as_object()
            .cloned()
            .unwrap_or_default()
            .into_iter()
            .map(|(key, value)| (key, value.as_str().unwrap_or("").to_owned()))
            .collect()
    };
    let code = fields.get("code").cloned().unwrap_or_else(|| {
        authorization
            .strip_prefix("Bearer token:")
            .unwrap_or("")
            .to_owned()
    });
    fake.calls.lock().unwrap().push(Call {
        method,
        path: uri.path().to_owned(),
        content_type,
        authorization,
        fields,
    });
    if uri.path().ends_with("/token") {
        if code == "deny" {
            return (
                StatusCode::BAD_REQUEST,
                Json(json!({"error": "access_denied"})),
            )
                .into_response();
        }
        assert_eq!(code, "allow", "unexpected provider code");
        return Json(json!({"access_token": "token:allow"})).into_response();
    }
    if uri.path().ends_with("/emails") {
        return Json(json!([{"email":"primary@example.com","verified":true,"primary":true}]))
            .into_response();
    }
    if uri.path().ends_with("/github/user") {
        return Json(json!({"id":123,"login":"octocat","name":"Octo Cat"})).into_response();
    }
    Json(json!({"id":"123","username":"discord-user","global_name":"Discord User","email":"primary@example.com","verified":true})).into_response()
}

struct Server {
    origin: String,
    client: reqwest::Client,
    fake: Fake,
    owner: WriterOwner,
    directory: PathBuf,
    app_task: tokio::task::JoinHandle<()>,
    app_stop: tokio::sync::oneshot::Sender<()>,
    fake_task: tokio::task::JoinHandle<()>,
}
impl Server {
    async fn start() -> Self {
        let mut suffix = [0; 12];
        getrandom::fill(&mut suffix).unwrap();
        let directory = std::env::temp_dir().join(format!("pp-auth-oauth-{}", hex::encode(suffix)));
        let owner = WriterOwner::open(&directory, Limits::default()).unwrap().0;
        let auth = owner
            .rebuild_auth_with_policy(
                AuthPolicy {
                    registration: RegistrationPolicy::Open,
                    session_tenant: SessionTenantPolicy::AccountTenant,
                    first_user: FirstUserTenant::NewUser,
                },
                AuthLifetimes::default(),
            )
            .unwrap();
        let fake_listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let fake_origin = format!("http://{}", fake_listener.local_addr().unwrap());
        let fake = Fake {
            calls: Arc::default(),
        };
        let fake_router = Router::new()
            .fallback(fake_request)
            .with_state(fake.clone());
        let fake_task = tokio::spawn(async move {
            axum::serve(fake_listener, fake_router).await.unwrap();
        });
        let credentials = |client_id: &str| {
            OAuthCredentials::new(client_id.into(), Secret::new(SECRET.into())).unwrap()
        };
        let mut providers = ProviderClient::new(
            Some(credentials("fixture-github-client")),
            Some(credentials("fixture-discord-client")),
        )
        .unwrap();
        providers
            .redirect_exchange_to_loopback_for_tests(&fake_origin)
            .unwrap();
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let origin = format!("http://{}", listener.local_addr().unwrap());
        let router = auth_router(
            AuthHttpConfig::new(&origin, CookieTransport::LoopbackHttp, true, None, false).unwrap(),
            auth,
            providers,
            ResetMailer::disabled(),
        );
        let (app_stop, rx) = tokio::sync::oneshot::channel();
        let app_task = tokio::spawn(async move {
            axum::serve(
                listener,
                router.into_make_service_with_connect_info::<SocketAddr>(),
            )
            .with_graceful_shutdown(async {
                let _ = rx.await;
            })
            .await
            .unwrap();
        });
        let client = reqwest::Client::builder()
            .redirect(reqwest::redirect::Policy::none())
            .no_proxy()
            .timeout(Duration::from_secs(10))
            .build()
            .unwrap();
        Self {
            origin,
            client,
            fake,
            owner,
            directory,
            app_task,
            app_stop,
            fake_task,
        }
    }

    async fn close(self) {
        self.app_stop.send(()).unwrap();
        self.app_task.await.unwrap();
        self.fake_task.abort();
        let _ = self.fake_task.await;
        self.owner.shutdown().unwrap();
        std::fs::remove_dir_all(self.directory).unwrap();
    }

    fn count(&self, sql: &str) -> i64 {
        let db = rusqlite::Connection::open(self.directory.join("print-partner.db")).unwrap();
        db.busy_timeout(Duration::from_secs(2)).unwrap();
        db.query_row(sql, [], |row| row.get(0)).unwrap()
    }

    async fn begin(&self, case: &Case, seen: &mut HashSet<String>) -> Issued {
        let path = match case.provider {
            Provider::Github => "/auth/github",
            Provider::Discord => "/auth/discord",
        };
        let response = self
            .client
            .get(format!("{}{path}", self.origin))
            .send()
            .await
            .unwrap();
        assert_eq!(response.status(), 302, "{}", case.id);
        let location = Url::parse(response.headers()["location"].to_str().unwrap()).unwrap();
        assert_eq!(
            location.host_str(),
            Some(match case.provider {
                Provider::Github => "github.com",
                Provider::Discord => "discord.com",
            })
        );
        let mut parameters: BTreeMap<String, Vec<String>> = BTreeMap::new();
        for (key, value) in location.query_pairs() {
            parameters
                .entry(key.into_owned())
                .or_default()
                .push(value.into_owned());
        }
        let state = parameters["state"].clone();
        assert_eq!(state.len(), 1, "{}", case.id);
        canonical(&state[0], seen);
        let cookies: Vec<_> = response.headers().get_all("set-cookie").iter().collect();
        assert_eq!(cookies.len(), 1, "{}", case.id);
        let (name, browser) = cookies[0]
            .to_str()
            .unwrap()
            .split(';')
            .next()
            .unwrap()
            .split_once('=')
            .unwrap();
        assert_eq!(name, "oauth_state");
        canonical(browser, seen);
        assert_ne!(
            browser, state[0],
            "rust browser binding must not equal state"
        );
        let challenge = match case.provider {
            Provider::Github => {
                assert_eq!(parameters["code_challenge_method"], ["S256".to_owned()]);
                let challenge = parameters["code_challenge"].clone();
                assert_eq!(challenge.len(), 1);
                canonical(&challenge[0], seen);
                Some(challenge[0].clone())
            }
            Provider::Discord => {
                assert!(!parameters.contains_key("code_challenge"));
                None
            }
        };
        assert_eq!(
            parameters["redirect_uri"],
            [format!("{}{}", self.origin, case.callback)]
        );
        assert_eq!(
            parameters["client_id"].as_slice(),
            std::slice::from_ref(&case.client_id)
        );
        Issued {
            state: state[0].clone(),
            browser: browser.to_owned(),
            challenge,
        }
    }

    async fn callback(
        &self,
        case: &Case,
        query: &[(&str, &str)],
        browser: Option<&str>,
    ) -> Observation {
        let mut target = Url::parse(&format!("{}{}", self.origin, case.callback)).unwrap();
        for (key, value) in query {
            target.query_pairs_mut().append_pair(key, value);
        }
        let mut request = self
            .client
            .get(target)
            .header("Sec-Fetch-Site", "cross-site");
        if let Some(browser) = browser {
            request = request.header("Cookie", format!("oauth_state={browser}"));
        }
        let response = request.send().await.unwrap();
        let status = response.status().as_u16();
        let location = response
            .headers()
            .get("location")
            .map(|value| value.to_str().unwrap().to_owned());
        assert!(response.headers().get_all("location").iter().count() <= 1);
        let mut cookies = Vec::new();
        for header in response.headers().get_all("set-cookie") {
            let mut parts = header.to_str().unwrap().split(';').map(str::trim);
            let (name, value) = parts.next().unwrap().split_once('=').unwrap();
            let mut attributes = BTreeMap::new();
            for part in parts {
                let (key, value) = part
                    .split_once('=')
                    .map_or((part, None), |(key, value)| (key, Some(value.to_owned())));
                assert!(
                    attributes.insert(key.to_ascii_lowercase(), value).is_none(),
                    "duplicate cookie attribute"
                );
            }
            cookies.push(Cookie {
                name: name.to_owned(),
                value: value.to_owned(),
                attributes,
            });
        }
        let bytes = response.bytes().await.unwrap();
        let body = if bytes.is_empty() {
            Value::Null
        } else {
            serde_json::from_slice(&bytes).unwrap()
        };
        Observation {
            status,
            location,
            cookies,
            body,
            sessions: self.count("SELECT count(*) FROM sessions"),
        }
    }
}

fn redact_sessions(mut observed: Observation, sessions: &mut Vec<String>) -> Observation {
    for cookie in &mut observed.cookies {
        if cookie.name != "pp_session" {
            continue;
        }
        assert!(
            cookie.value.len() > 16 && !sessions.contains(&cookie.value),
            "session cookie missing or reused"
        );
        sessions.push(cookie.value.clone());
        cookie.value = format!("<session:{}>", sessions.len());
    }
    observed
}

fn assert_exchange(case: &Case, calls: &[Call], challenge: Option<&str>, denied: bool) {
    let prefix = match case.provider {
        Provider::Github => "/github",
        Provider::Discord => "/discord",
    };
    if denied {
        assert_eq!(calls.len(), 1, "{}", case.id);
        assert_eq!(calls[0].path, format!("{prefix}/token"));
        assert!(
            calls[0]
                .fields
                .get("code")
                .is_some_and(|code| code == "deny")
        );
        return;
    }
    let mut expected = vec![format!("{prefix}/token"), format!("{prefix}/user")];
    if case.provider == Provider::Github {
        expected.push(format!("{prefix}/emails"));
    }
    assert_eq!(
        calls
            .iter()
            .map(|call| call.path.clone())
            .collect::<Vec<_>>(),
        expected,
        "{}",
        case.id
    );
    let token = &calls[0];
    assert_eq!(token.method, Method::POST);
    let keys: Vec<_> = token.fields.keys().cloned().collect();
    match case.provider {
        Provider::Github => {
            assert_eq!(
                keys.iter().map(String::as_str).collect::<Vec<_>>(),
                [
                    "client_id",
                    "client_secret",
                    "code",
                    "code_verifier",
                    "redirect_uri"
                ]
            );
            assert!(token.content_type.contains("application/json"));
            let verifier = token
                .fields
                .get("code_verifier")
                .map(String::as_str)
                .unwrap();
            assert!(
                s256(verifier) == challenge.unwrap(),
                "github pkce verifier does not match the authorization challenge"
            );
        }
        Provider::Discord => {
            assert_eq!(
                keys.iter().map(String::as_str).collect::<Vec<_>>(),
                [
                    "client_id",
                    "client_secret",
                    "code",
                    "grant_type",
                    "redirect_uri"
                ]
            );
            assert!(
                token
                    .content_type
                    .contains("application/x-www-form-urlencoded")
            );
            assert_eq!(
                token.fields.get("grant_type").map(String::as_str),
                Some("authorization_code")
            );
            assert!(challenge.is_none());
        }
    }
    assert!(
        token
            .fields
            .get("client_secret")
            .is_some_and(|value| value == SECRET)
    );
    assert_eq!(
        token.fields.get("client_id").map(String::as_str),
        Some(case.client_id.as_str())
    );
    assert_eq!(token.fields.get("code").map(String::as_str), Some("allow"));
    for call in &calls[1..] {
        assert_eq!(call.method, Method::GET);
        assert!(
            call.authorization == "Bearer token:allow",
            "profile authorization changed"
        );
    }
}

fn assert_step(case: &Case, step: &Step, observed: &Observation, sessions: &mut Vec<String>) {
    let redacted = redact_sessions(observed.clone(), sessions);
    match step.kind {
        Kind::MissingState | Kind::ChangedState => assert_eq!(&redacted, &step.node, "{}", case.id),
        Kind::Denied => {
            assert_eq!(step.node.status, 401, "{}", case.id);
            assert_eq!(step.node.body, json!({"detail": "access_denied"}));
            assert_eq!(step.node.sessions, 0);
            assert!(step.node.cookies.is_empty());
            assert_eq!(redacted.status, 401, "{}", case.id);
            assert_eq!(redacted.body, json!({"detail": "OAuth failed"}));
            assert!(redacted.cookies.is_empty() && redacted.location.is_none());
            assert_eq!(redacted.sessions, 0);
        }
        Kind::Allow => {
            assert_eq!(step.node.status, 302, "{}", case.id);
            assert_eq!(step.node.location.as_deref(), Some("/"));
            assert_eq!(step.node.body, Value::Null);
            assert_eq!(step.node.sessions, 1);
            assert_eq!(step.node.cookies.len(), 2);
            assert_eq!(step.node.cookies[0].name, "pp_session");
            assert_eq!(step.node.cookies[0].value, "<session:1>");
            assert_eq!(step.node.cookies[0].attributes, session_attributes());
            assert_eq!(step.node.cookies[1], node_clear());
            assert_eq!(redacted.status, 302, "{}", case.id);
            assert_eq!(redacted.location.as_deref(), Some("/"));
            assert_eq!(redacted.body, Value::Null);
            assert_eq!(redacted.sessions, 1);
            assert_eq!(redacted.cookies[0].name, "pp_session");
            assert_eq!(redacted.cookies[0].value, "<session:1>");
            assert_eq!(redacted.cookies[0].attributes, session_attributes());
            assert_eq!(redacted.cookies[1], rust_clear());
            assert!(success_contract(&redacted), "{}", case.id);
            let mut changed = redacted.clone();
            changed.location = Some("/elsewhere".into());
            assert!(
                !success_contract(&changed),
                "changed redirect must fail the comparison"
            );
        }
        Kind::Replay => {
            let success = step.node.status == 302;
            if success {
                assert_eq!(step.node.sessions, 2, "{}", case.id);
                assert_eq!(step.node.cookies[0].value, "<session:2>");
                assert_eq!(step.node.location.as_deref(), Some("/"));
            } else {
                assert_eq!(step.node.status, 401, "{}", case.id);
                assert_eq!(step.node.sessions, 0);
            }
            assert!(consumed_contract(&redacted, success), "{}", case.id);
            let mut reused = redacted.clone();
            reused.sessions += 1;
            assert!(
                !consumed_contract(&reused, success),
                "reused state must fail the comparison"
            );
        }
    }
}

fn success_contract(observed: &Observation) -> bool {
    observed.status == 302
        && observed.location.as_deref() == Some("/")
        && observed.body == Value::Null
        && observed.sessions == 1
        && observed.cookies.len() == 2
        && observed.cookies[0].name == "pp_session"
        && observed.cookies[0].attributes == session_attributes()
        && observed.cookies[1] == rust_clear()
}

fn consumed_contract(observed: &Observation, after_success: bool) -> bool {
    observed.status == 400
        && observed.body == json!({"detail": "Invalid OAuth state"})
        && observed.cookies.is_empty()
        && observed.location.is_none()
        && observed.sessions == if after_success { 1 } else { 0 }
}

#[tokio::test]
async fn oauth_callback_matches_node_except_one_time_state_consumption() {
    let mut seen = HashSet::new();
    for case in fixture().cases {
        let server = Server::start().await;
        let mut sessions = Vec::new();
        let mut issued: Option<Issued> = None;
        let mut sent: Option<Sent> = None;
        for step in &case.steps {
            let (query, browser): (Vec<(&str, &str)>, Option<&str>) = match step.kind {
                Kind::MissingState => {
                    issued = Some(server.begin(&case, &mut seen).await);
                    (
                        vec![("code", "allow")],
                        Some(issued.as_ref().unwrap().browser.as_str()),
                    )
                }
                Kind::ChangedState => {
                    issued = Some(server.begin(&case, &mut seen).await);
                    (
                        vec![("code", "allow"), ("state", "changed-state")],
                        Some(issued.as_ref().unwrap().browser.as_str()),
                    )
                }
                Kind::Denied | Kind::Allow => {
                    let flow = server.begin(&case, &mut seen).await;
                    sent = Some(Sent {
                        code: step.kind.code().unwrap(),
                        state: flow.state.clone(),
                        browser: flow.browser.clone(),
                    });
                    issued = Some(flow);
                    (
                        vec![
                            ("code", sent.as_ref().unwrap().code),
                            ("state", sent.as_ref().unwrap().state.as_str()),
                        ],
                        Some(sent.as_ref().unwrap().browser.as_str()),
                    )
                }
                Kind::Replay => {
                    let sent = sent.as_ref().unwrap();
                    (
                        vec![("code", sent.code), ("state", sent.state.as_str())],
                        Some(sent.browser.as_str()),
                    )
                }
            };
            let observed = server.callback(&case, &query, browser).await;
            assert_step(&case, step, &observed, &mut sessions);
        }
        {
            let calls = server.fake.calls.lock().unwrap();
            match case.steps[0].kind {
                Kind::MissingState | Kind::ChangedState => assert!(calls.is_empty(), "{}", case.id),
                Kind::Denied => assert_exchange(&case, &calls, None, true),
                Kind::Allow => assert_exchange(
                    &case,
                    &calls,
                    issued.as_ref().and_then(|flow| flow.challenge.as_deref()),
                    false,
                ),
                Kind::Replay => unreachable!(),
            }
        }
        let users = server.count("SELECT count(*) FROM users");
        let identities = server.count("SELECT count(*) FROM auth_identities");
        if case.steps.iter().any(|step| step.kind == Kind::Allow) {
            assert_eq!((users, identities), (1, 1), "{}", case.id);
            let db = rusqlite::Connection::open(server.directory.join("print-partner.db")).unwrap();
            let pair: (String, String) = db
                .query_row(
                    "SELECT provider, provider_user_id FROM auth_identities",
                    [],
                    |row| Ok((row.get(0)?, row.get(1)?)),
                )
                .unwrap();
            assert_eq!(
                pair,
                (
                    match case.provider {
                        Provider::Github => "github",
                        Provider::Discord => "discord",
                    }
                    .to_owned(),
                    "123".to_owned()
                )
            );
        } else {
            assert_eq!((users, identities), (0, 0), "{}", case.id);
        }
        server.close().await;
    }
}

