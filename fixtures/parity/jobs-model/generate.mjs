// Generates the jobs-model parity golden from the TypeScript job result
// contracts. Run from the repo root after `npm --prefix web ci`:
//   node fixtures/parity/jobs-model/generate.mjs          # write
//   node fixtures/parity/jobs-model/generate.mjs --check  # verify, no writes
// Needs Node >= 22.18 (built-in type stripping). The contracts import zod, so
// the web dependencies must be installed.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const contractsSource = "web/packages/contracts/src/accepted-plates.ts";
const goldenPath = join(here, "jobs-model.json");
const check = process.argv.includes("--check");

const { parseAcceptedPlanBasis, parseAcceptedPlateExportJobResult, parseDirectExportJobResult } =
  await import(pathToFileURL(join(root, contractsSource)).href);

const hex = (digit) => digit.repeat(64);
const basis = {
  profile_id: 7,
  plan_version: 11,
  plan_revision_id: 13,
  plan_revision_digest: hex("d"),
  required_unit_mapping_digest: hex("e"),
};
const plate = (ordinal) => ({
  plate_id: `plate_${String(ordinal).repeat(32)}`,
  ordinal,
  filename: `Plate ${ordinal}.3mf`,
  download_url: `/exports/plates/plate-${ordinal}.3mf`,
});
const acceptedPlates = (plates) => ({
  format: "accepted-plate-export-job-v1",
  profile_id: 7,
  basis,
  plate_revision_id: 21,
  plate_revision_number: 3,
  layout_digest: hex("a"),
  download_url: plates.length === 1 ? plates[0].download_url : "/exports/plates/bundle.zip",
  manifest_download_url: "/exports/plates/manifest.json",
  bundle_download_url: "/exports/plates/bundle.zip",
  plates,
});

// Each result is the object Node returns after validating it with the
// contract parser used by the job runner and its HTTP readers.
const results = [
  {
    id: "accepted-plates-single",
    kind: "export-accepted-plate-3mf",
    node: parseAcceptedPlateExportJobResult(acceptedPlates([plate(1)])),
  },
  {
    id: "accepted-plates-two",
    kind: "export-accepted-plate-3mf",
    node: parseAcceptedPlateExportJobResult(acceptedPlates([plate(1), plate(2)])),
  },
  {
    id: "direct-3mf",
    kind: "export-direct-3mf",
    node: parseDirectExportJobResult({
      format: "direct-export-3mf-job-v1",
      profile_id: 7,
      basis,
      download_url: "/exports/direct/Build%207.3mf",
      filename: "Build 7.3mf",
      tokens: [`ppu_${"0".repeat(32)}`, `ppu_${"f".repeat(32)}`],
    }),
  },
];

// The checklist completion claim seals an accepted Plan basis. Node's basis
// contract decides which seals are well formed.
const basisCases = [
  ["valid", {}],
  ["zero-plan-version", { plan_version: 0 }],
  ["zero-revision", { plan_revision_id: 0 }],
  ["unsafe-plan-version", { plan_version: 2 ** 53 }],
  ["unsafe-revision", { plan_revision_id: 2 ** 53 }],
  ["max-safe-identifiers", { plan_version: Number.MAX_SAFE_INTEGER, plan_revision_id: Number.MAX_SAFE_INTEGER }],
  ["uppercase-revision-digest", { plan_revision_digest: hex("D") }],
  ["short-revision-digest", { plan_revision_digest: "d".repeat(63) }],
  ["non-hex-mapping-digest", { required_unit_mapping_digest: hex("g") }],
].map(([id, patch]) => {
  const input = { ...basis, ...patch };
  let accepted = true;
  try {
    parseAcceptedPlanBasis(input);
  } catch {
    accepted = false;
  }
  return { id, input, accepted };
});

// One case per line keeps the golden reviewable.
const cases = (items) => items.map((item) => `    ${JSON.stringify(item)}`).join(",\n");
const generated = `@generated by fixtures/parity/jobs-model/generate.mjs from Node ${process.version}. Do not edit.`;
const text = `{
  "generated": ${JSON.stringify(generated)},
  "source": ${JSON.stringify(contractsSource)},
  "results": [
${cases(results)}
  ],
  "accepted_basis": [
${cases(basisCases)}
  ]
}
`;

let current = null;
try {
  current = readFileSync(goldenPath, "utf8");
} catch {}
if (current !== text) {
  if (check) {
    console.error(`out of date ${relative(root, goldenPath)}`);
    process.exit(1);
  }
  writeFileSync(goldenPath, text);
}
console.log(JSON.stringify({ results: results.length, acceptedBasis: basisCases.length, check }));
