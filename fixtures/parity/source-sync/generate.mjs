// Generates the source-sync parity golden from Node's InProcessJobRunner. Run
// from the repo root after `npm --prefix web ci --ignore-scripts`:
//   node fixtures/parity/source-sync/generate.mjs          # write
//   node fixtures/parity/source-sync/generate.mjs --check  # verify, no writes
// The runner imports workspace TypeScript, so the generator reruns itself
// under web's tsx loader with the `development` export condition.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const runnerSource = "web/apps/server/src/services/job-runner.ts";
const output = join(here, "source-sync.json");

// An id with no Source (99), then one Local Source (7), in payload order.
const projectIds = [99, 7];

if (process.argv.includes("--probe")) {
  const { InProcessJobRunner } = await import(pathToFileURL(join(root, runnerSource)).href);
  const directory = mkdtempSync(join(tmpdir(), "pp-source-sync-probe-"));
  try {
    writeFileSync(join(directory, "README.md"), "# Local\n");
    const rows = { 7: { id: 7, name: "Local", sourceKind: "local", localPath: directory, lastCommitSha: null } };
    const repo = {
      getSetting: () => null,
      setSetting: () => undefined,
      listSources: () => [],
      getProjectRow: (id) => rows[id],
      getSourceActivationObservation: (id) => (rows[id] ? { id } : undefined),
      replaceSourceDocs: () => undefined,
      markSourceSynced: () => undefined,
    };
    const runner = new InProcessJobRunner({
      getRepo: () => repo,
      reposDir: join(directory, "repos"),
      exportsDir: join(directory, "exports"),
      dataDir: directory,
    });
    const jobId = await runner.start("sync", { project_ids: projectIds }, "tenant-a");
    const attempts = [];
    runner.subscribe(jobId, "tenant-a", (event) => {
      if (event.message?.startsWith("Syncing ")) attempts.push(event.message);
    });
    let snapshot;
    for (;;) {
      snapshot = await runner.get(jobId, "tenant-a");
      if (snapshot.status !== "pending" && snapshot.status !== "running") break;
      await new Promise((resolve) => setTimeout(resolve, 5));
    }
    process.stdout.write(`\n${JSON.stringify({ status: snapshot.status, attempts, result: snapshot.result })}`);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
  process.exit(0);
}

const tsx = join(root, "web/node_modules/tsx/dist/esm/index.mjs");
const probe = JSON.parse(
  execFileSync(
    process.execPath,
    ["--conditions=development", "--import", pathToFileURL(tsx).href, fileURLToPath(import.meta.url), "--probe"],
    { cwd: join(root, "web/apps/server"), encoding: "utf8" },
  )
    .split("\n")
    .at(-1),
);
const generated = "@generated by fixtures/parity/source-sync/generate.mjs. Do not edit.";
const text = `${JSON.stringify({ generated, source: runnerSource, project_ids: projectIds, ...probe }, null, 2)}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== text) throw new Error("source-sync.json is out of date");
} else {
  writeFileSync(output, text);
}
console.log(JSON.stringify({ attempts: probe.attempts.length, check: process.argv.includes("--check") }));
