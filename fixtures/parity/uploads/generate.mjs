// Generate Node supplied-upload admission results. Run from the repo root, with or without --check.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, truncateSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const source = "web/apps/server/src/services/archive-import.ts";
const output = join(here, "uploads.json");
const MIB = 1024 * 1024;
const inputs = [
  { id: "empty", files: [] },
  { id: "too_many", files: Array.from({ length: 10_001 }, (_, index) => ({ path: `part-${index}.stl`, size: 1 })) },
  { id: "at_limit", files: [{ path: "part.stl", size: 256 * MIB }] },
  { id: "over_limit", files: [{ path: "part.stl", size: 256 * MIB + 1 }] },
  { id: "nested", files: [{ path: "parts/a.stl", size: 3 }, { path: "README.md", size: 3 }] },
  { id: "parent", files: [{ path: "../part.stl", size: 3 }] },
  { id: "duplicate", files: [{ path: "part.stl", size: 3 }, { path: "part.stl", size: 3 }] },
  { id: "case_duplicate", files: [{ path: "Part.stl", size: 3 }, { path: "part.stl", size: 3 }] },
  { id: "backslash", files: [{ path: "parts\\a.stl", size: 3 }] },
  { id: "absolute", files: [{ path: "/part.stl", size: 3 }] },
  { id: "leading_slashes", files: [{ path: "//parts\\A.stl", size: 3 }] },
  { id: "canonical_duplicate", files: [{ path: "/parts\\a.stl", size: 3 }, { path: "parts/a.stl", size: 3 }] },
  { id: "canonical_case_duplicate", files: [{ path: "parts/a.stl", size: 3 }, { path: "\\Parts\\A.stl", size: 3 }] },
];

if (process.argv.includes("--probe")) {
  const archive = await import(pathToFileURL(join(root, source)).href);
  const limits = await import(pathToFileURL(join(root, "web/apps/server/src/services/upload-limits.ts")).href);
  const cases = [];
  for (const input of inputs) {
    const directory = mkdtempSync(join(tmpdir(), "pp-uploads-probe-"));
    try {
      const files = input.files.map((file, index) => {
        const path = join(directory, `upload-${index}`);
        if (input.id !== "too_many") {
          writeFileSync(path, "");
          truncateSync(path, file.size);
        }
        return { relativePath: file.path, path };
      });
      const staging = join(directory, "staging");
      mkdirSync(staging);
      let result;
      try {
        const { fileCount, stlCount, extractDir } = archive.writeUploadedFiles(files, staging);
        const written = readdirSync(extractDir, { recursive: true, withFileTypes: true })
          .filter((entry) => entry.isFile())
          .map((entry) => relative(extractDir, join(entry.parentPath, entry.name)).split(sep).join("/"))
          .sort();
        result = { fileCount, stlCount, paths: written };
      } catch (error) {
        result = { error: error.message };
      }
      cases.push({ id: input.id, result });
    } finally {
      rmSync(directory, { recursive: true, force: true });
    }
  }
  process.stdout.write(JSON.stringify({
    limits: { max_source_upload_bytes: limits.MAX_SOURCE_UPLOAD_BYTES, max_source_upload_files: archive.MAX_SOURCE_UPLOAD_FILES },
    cases,
  }));
} else {
  const probe = execFileSync(process.execPath, [
    "--conditions=development", "--import", pathToFileURL(join(root, "web/node_modules/tsx/dist/esm/index.mjs")).href,
    fileURLToPath(import.meta.url), "--probe",
  ], { cwd: join(root, "web/apps/server"), encoding: "utf8" });
  const { limits, cases } = JSON.parse(probe);
  const recorded = cases.map((entry) => {
    const files = inputs.find((input) => input.id === entry.id).files;
    return { id: entry.id, files: entry.id === "too_many" ? { count: files.length } : files, result: entry.result };
  });
  const header = JSON.stringify({ generated: "@generated by fixtures/parity/uploads/generate.mjs. Do not edit.", source, limits });
  const text = `${header.slice(0, -1)},\n"cases":[\n${recorded.map((entry) => JSON.stringify(entry)).join(",\n")}\n]}\n`;
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== text) throw new Error("uploads.json is out of date");
  } else {
    writeFileSync(output, text);
  }
  console.log(JSON.stringify({ cases: cases.length, check: process.argv.includes("--check") }));
}
