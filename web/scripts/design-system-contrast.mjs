#!/usr/bin/env node
/**
 * Generate the contrast tables in docs/design-system.md from the tokens that
 * actually ship in web/apps/web/src/index.css, and check the token set.
 *
 *   node web/scripts/design-system-contrast.mjs           print the tables
 *   node web/scripts/design-system-contrast.mjs --write   rewrite the doc block
 *   node web/scripts/design-system-contrast.mjs --check   fail on any problem
 *
 * --check fails when:
 * - the generated block in the doc does not match index.css (stale tokens);
 * - a text ink is below 4.5:1 or a control edge below 3:1 on any surface, in
 *   light, dark, light high contrast or dark high contrast;
 * - a printer status from lib/statusTone.ts has no `--printer-*` token in a
 *   variant, a token has no status, or two statuses share a color (forced
 *   colors is exempt: the browser replaces authored colors with system ones,
 *   so every status maps to CanvasText and keeps its glyph and words);
 * - --background, --card or --popover is not the surface the tables measure;
 * - reduced motion leaves a motion token above 0 ms on rebuilt UI;
 * - a rebuilt-UI rule (`:root[data-desktop-rebuild] ...`), a file under
 *   web/apps/web/src/rebuild/, or a file those files import uses a raw color,
 *   length or duration.
 *
 * --css, --doc, --status and --rebuild-dir point the check at other files.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : fallback;
};
const cssPath = arg("--css", join(here, "../apps/web/src/index.css"));
const docPath = arg("--doc", join(here, "../../docs/design-system.md"));
const statusPath = arg("--status", join(here, "../apps/web/src/lib/statusTone.ts"));
const rebuildDir = arg("--rebuild-dir", join(here, "../apps/web/src/rebuild"));

const ROOT = ":root";
const DARK = ".dark";
const REBUILD = ":root[data-desktop-rebuild]";
const REBUILD_DARK = ":root[data-desktop-rebuild].dark";
const HIGH_CONTRAST = "@media (prefers-contrast: more)";
const FORCED_COLORS = "@media (forced-colors: active)";
const REDUCED_MOTION = "@media (prefers-reduced-motion: reduce)";

const SURFACES = ["surface-sunken", "surface-base", "surface-raised", "surface-overlay"];
const TEXT_INKS = [
  ["foreground", "foreground"],
  ["muted-foreground", "muted-foreground"],
  ["primary", "primary (signal cyan, also the focus ring)"],
  ["success", "success"],
  ["warning", "warning"],
  ["info", "info"],
  ["destructive", "destructive"],
];
const UI_INKS = ["border-strong", "ring"];
const ALIASES = [["background", "surface-base"], ["card", "surface-raised"], ["popover", "surface-overlay"]];

const DOC_START = "<!-- design-tokens:start (generated by web/scripts/design-system-contrast.mjs --write) -->";
const DOC_END = "<!-- design-tokens:end -->";

/** Leaf rules with the @media they sit in. Other at-rules are transparent. */
function parseRules(source, media = null, out = []) {
  let i = 0;
  while (i < source.length) {
    const open = source.indexOf("{", i);
    if (open < 0) break;
    let prelude = source.slice(i, open);
    prelude = prelude.slice(prelude.lastIndexOf(";") + 1).replace(/\s+/g, " ").trim();
    let depth = 0;
    let close = open;
    for (; close < source.length; close++) {
      if (source[close] === "{") depth++;
      else if (source[close] === "}" && --depth === 0) break;
    }
    const body = source.slice(open + 1, close);
    if (prelude.startsWith("@")) parseRules(body, prelude.startsWith("@media") ? prelude : media, out);
    else out.push({ media, selector: prelude, body });
    i = close + 1;
  }
  return out;
}

function declarations(body) {
  const found = new Map();
  for (const part of body.split(";")) {
    const colon = part.indexOf(":");
    if (colon < 0) continue;
    found.set(part.slice(0, colon).trim(), part.slice(colon + 1).trim());
  }
  return found;
}

function hslToRgb([h, s, l]) {
  s /= 100;
  l /= 100;
  const c = (1 - Math.abs(2 * l - 1)) * s;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = l - c / 2;
  const [r, g, b] = [
    [c, x, 0], [x, c, 0], [0, c, x], [0, x, c], [x, 0, c], [c, 0, x],
  ][Math.floor(h / 60) % 6];
  return [r + m, g + m, b + m];
}

function luminance(rgb) {
  const [r, g, b] = rgb.map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function ratio(a, b) {
  const [x, y] = [luminance(a), luminance(b)];
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}

const css = readFileSync(cssPath, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
const rules = parseRules(css);
const problems = [];

/** Declarations of every rule with this selector and media, in source order. */
function pick(selector, media = null) {
  const merged = new Map();
  for (const rule of rules) {
    if (rule.selector === selector && rule.media === media) {
      for (const [k, v] of declarations(rule.body)) merged.set(k, v);
    }
  }
  return merged;
}

const merge = (...maps) => new Map(maps.flatMap((m) => [...m]));
const light = merge(pick(ROOT), pick(REBUILD));
const dark = merge(pick(ROOT), pick(DARK), pick(REBUILD), pick(REBUILD_DARK));
const THEMES = [
  ["Dark", dark],
  ["Light", light],
  ["Dark high contrast", merge(dark, pick(REBUILD, HIGH_CONTRAST), pick(REBUILD_DARK, HIGH_CONTRAST))],
  ["Light high contrast", merge(light, pick(REBUILD, HIGH_CONTRAST))],
];

// A light rebuild rule outranks `.dark`, so its dark twin must override every
// token it sets, or the light value leaks into dark mode.
for (const media of [null, HIGH_CONTRAST]) {
  const darkKeys = pick(REBUILD_DARK, media);
  for (const key of pick(REBUILD, media).keys()) {
    if (!darkKeys.has(key)) problems.push(`${media ?? "base"}: ${REBUILD_DARK} does not set ${key}`);
  }
}

function color(theme, name, seen = new Set()) {
  const value = theme.get(`--${name}`);
  if (!value || seen.has(name)) return null;
  const ref = /^var\(--([\w-]+)\)$/.exec(value);
  if (ref) return color(theme, ref[1], seen.add(name));
  const hsl = /^hsl\(\s*([\d.]+)\s+([\d.]+)%\s+([\d.]+)%\s*\)$/.exec(value);
  return hsl ? hslToRgb([Number(hsl[1]), Number(hsl[2]), Number(hsl[3])]) : null;
}

const statusSource = readFileSync(statusPath, "utf8");
const kindsBlock = /PRINTER_STATUS_KINDS = \[([\s\S]*?)\] as const/.exec(statusSource);
const printerKinds = kindsBlock ? [...kindsBlock[1].matchAll(/"([\w]+)"/g)].map((m) => m[1]) : [];
if (!printerKinds.length) problems.push(`${statusPath}: no PRINTER_STATUS_KINDS`);
if (printerKinds.includes("queued")) problems.push("queued is a job state and must not be a printer status");
const printerTokens = printerKinds.map((kind) => `printer-${kind.replaceAll("_", "-")}`);

for (const [selector, media, label] of [
  [REBUILD, null, "light"],
  [REBUILD_DARK, null, "dark"],
  [REBUILD, HIGH_CONTRAST, "light high contrast"],
  [REBUILD_DARK, HIGH_CONTRAST, "dark high contrast"],
  [REBUILD, FORCED_COLORS, "forced colors"],
]) {
  const set = [...pick(selector, media).keys()].filter((k) => k.startsWith("--printer-"));
  for (const token of printerTokens) {
    if (!set.includes(`--${token}`)) problems.push(`${label}: missing --${token}`);
  }
  for (const key of set) {
    if (!printerTokens.includes(key.slice(2))) problems.push(`${label}: ${key} matches no printer status`);
  }
}

const TABLE_INKS = [
  ...TEXT_INKS,
  ...printerTokens.map((t) => [t, t]),
  ["border-strong", "border-strong"],
];

function table(theme) {
  const rows = ["| Ink | sunken | base | raised | overlay |", "| --- | --- | --- | --- | --- |"];
  let floor = Infinity;
  for (const [name, label] of TABLE_INKS) {
    const ink = color(theme, name);
    if (!ink) continue;
    const cells = SURFACES.map((s) => {
      const r = ratio(ink, color(theme, s));
      if (name !== "border-strong") floor = Math.min(floor, r);
      return r.toFixed(2);
    });
    rows.push(`| ${label} | ${cells.join(" | ")} |`);
  }
  return { markdown: rows.join("\n"), floor };
}

const sections = [];
const floors = [];
for (const [label, theme] of THEMES) {
  const { markdown, floor } = table(theme);
  sections.push(`${label}:`, "", markdown, "");
  floors.push(`${label.toLowerCase()} ${floor.toFixed(2)}`);

  for (const s of SURFACES) {
    if (!color(theme, s)) problems.push(`${label}: --${s} is not an hsl() color`);
  }
  // The tables measure the four surfaces; the backgrounds UI uses must be them.
  for (const [alias, surface] of ALIASES) {
    if (theme.get(`--${alias}`) !== `var(--${surface})`) {
      problems.push(`${label}: --${alias} must be var(--${surface}) for the contrast tables to hold`);
    }
  }
  const textNames = [...TEXT_INKS.map(([n]) => n), ...printerTokens];
  for (const name of [...textNames, ...UI_INKS]) {
    const ink = color(theme, name);
    if (!ink) {
      problems.push(`${label}: --${name} is not an hsl() color`);
      continue;
    }
    const min = textNames.includes(name) ? 4.5 : 3;
    for (const s of SURFACES) {
      const r = ratio(ink, color(theme, s));
      if (r < min) problems.push(`${label}: --${name} on --${s} is ${r.toFixed(2)}:1, below ${min}:1`);
    }
  }

  const byColor = new Map();
  for (const token of printerTokens) {
    const rgb = color(theme, token);
    if (!rgb) continue;
    const key = rgb.map((v) => Math.round(v * 255)).join(",");
    if (byColor.has(key)) problems.push(`${label}: --${token} and --${byColor.get(key)} share a color`);
    else byColor.set(key, token);
  }
}
const generated = [...sections, `Text floor: ${floors.join(", ")}.`].join("\n");

// Reduced motion: every duration token is 0 ms on rebuilt UI, and the
// catch-all rule reads it.
const reduced = pick(REBUILD, REDUCED_MOTION);
for (const [key, value] of pick(ROOT)) {
  if (key.startsWith("--motion-") && /^[\d.]+m?s$/.test(value) && reduced.get(key) !== "0ms") {
    problems.push(`reduced motion: ${key} is not 0ms under ${REBUILD}`);
  }
}
const catchAll = rules.find((r) => r.media === REDUCED_MOTION && r.selector.startsWith(`${REBUILD} *`));
const catchAllDecls = catchAll ? declarations(catchAll.body) : new Map();
for (const prop of ["animation-duration", "animation-delay", "transition-duration", "transition-delay"]) {
  const value = catchAllDecls.get(prop) ?? "";
  if (!/^var\(--motion-[\w-]+\) !important$/.test(value)) {
    problems.push(`reduced motion: ${REBUILD} * must set ${prop} from a motion token`);
  }
}

// Scoping: high contrast, forced colors and printer tokens never touch the
// app with the toggle off.
for (const rule of rules) {
  const scoped = rule.selector.split(",").every((s) => s.trim().startsWith(REBUILD));
  const decls = declarations(rule.body);
  const needsScope =
    rule.media === HIGH_CONTRAST ||
    rule.media === FORCED_COLORS ||
    [...decls.keys()].some((k) => k.startsWith("--printer-"));
  if (needsScope && !scoped) problems.push(`${rule.media ?? ""} ${rule.selector}: must be under ${REBUILD}`.trim());
  if (!scoped) continue;
  for (const [prop, value] of decls) {
    if (prop.startsWith("--")) continue;
    if (/#[0-9a-f]{3,8}\b|\b(?:rgb|hsl)a?\(|\d(?:px|rem|em|ms|s|%)\b/i.test(value)) {
      problems.push(`${rule.selector}: ${prop}: ${value} is a raw value, use a token`);
    }
  }
}

// Rebuilt screens: tokens only.
const RAW_IN_SOURCE = [
  [/#[0-9a-fA-F]{3,8}\b(?![\w-])/, "hex color"],
  [/\b(?:rgb|hsl)a?\(/, "color function"],
  [/\b[\w:-]+-\[[^\]]*(?:\d(?:px|rem|em|ms|s|%)|#[0-9a-fA-F]|rgb|hsl)[^\]]*\]/, "Tailwind arbitrary value"],
  [/\b(?:text|bg|border|ring|fill|stroke|from|to|via)-(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3}\b/, "raw palette class"],
  [/\b(?:duration|delay)-\d+\b/, "raw duration class"],
  [/\b\d+(?:\.\d+)?(?:px|rem|ms)\b/, "raw length or duration"],
];
function* walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) yield* walk(full);
    else if (/\.(tsx?|css)$/.test(entry) && !/\.test\./.test(entry)) yield full;
  }
}

// A rebuilt screen renders whatever it imports, so follow relative and `@/`
// imports out of src/rebuild/ and hold those files to the same rule. Static
// imports only: a computed dynamic import() path is not followed.
const srcRoot = dirname(rebuildDir);
function resolveImport(from, spec) {
  let base;
  if (spec.startsWith("./") || spec.startsWith("../")) base = join(dirname(from), spec);
  else if (spec.startsWith("@/")) base = join(srcRoot, spec.slice(2));
  else return null;
  const candidates = [base, `${base}.ts`, `${base}.tsx`, join(base, "index.ts"), join(base, "index.tsx")];
  return candidates.find((c) => /\.(tsx?|css)$/.test(c) && existsSync(c) && statSync(c).isFile()) ?? null;
}
if (existsSync(rebuildDir)) {
  const queue = [...walk(rebuildDir)];
  const seen = new Set(queue);
  while (queue.length) {
    const file = queue.shift();
    const raw = readFileSync(file, "utf8");
    const source = raw.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, "");
    for (const [re, what] of RAW_IN_SOURCE) {
      const match = re.exec(source);
      if (match) problems.push(`${relative(process.cwd(), file)}: ${what} "${match[0]}"`);
    }
    for (const [, spec] of raw.matchAll(/(?:from|import)\s*["']([^"']+)["']/g)) {
      const target = resolveImport(file, spec);
      if (target && !seen.has(target) && !/\.test\./.test(target) && target !== cssPath) {
        seen.add(target);
        queue.push(target);
      }
    }
  }
}

const block = `${DOC_START}\n\n${generated}\n\n${DOC_END}`;
const doc = readFileSync(docPath, "utf8");
const docBlock = new RegExp(`${DOC_START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${DOC_END}`);

if (argv.includes("--write")) {
  if (!docBlock.test(doc)) throw new Error(`${docPath} has no ${DOC_START} block`);
  writeFileSync(docPath, doc.replace(docBlock, () => block));
  process.stdout.write(`wrote ${relative(process.cwd(), docPath)}\n`);
} else if (argv.includes("--check")) {
  if (!doc.includes(block)) {
    problems.push("docs/design-system.md token tables are stale: run design-system-contrast.mjs --write");
  }
  if (problems.length) {
    process.stderr.write(`design tokens: ${problems.length} problem(s)\n`);
    for (const p of problems) process.stderr.write(`  ${p}\n`);
    process.exit(1);
  }
  process.stdout.write("design tokens: doc tables fresh, contrast AA, printer colors unique, motion and scope ok\n");
} else {
  process.stdout.write(`${generated}\n`);
  for (const p of problems) process.stderr.write(`  ${p}\n`);
}
