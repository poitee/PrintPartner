// Generates web/packages/rust-client/src from pp-api's client contract.
// Separate from generate.mjs so rust-wire.generated.ts, whose header pins
// generate.mjs's hash, stays byte-identical.
import process from "node:process";
import console from "node:console";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { URL, fileURLToPath } from "node:url";

export const generatorVersion = "rust-client-zod/1";
const repo = fileURLToPath(new URL("../../../", import.meta.url));
export const packageSource = join(repo, "web/packages/rust-client/src");
const keywords = new Set(["$schema", "$ref", "definitions", "title", "description", "type", "properties", "required", "additionalProperties", "enum", "anyOf", "oneOf", "items", "minItems", "maxItems", "minimum", "maximum", "minLength", "maxLength", "pattern", "format", "x-unicode-scalar"]);
const MAX_SAFE = Number.MAX_SAFE_INTEGER;
// Integer formats schemars emits for Rust primitives. 64-bit and pointer-size
// integers are bounded to the JavaScript safe range: a larger value is refused
// rather than silently rounded.
const integerFormats = {
  int8: [-128, 127], uint8: [0, 255], int16: [-32768, 32767], uint16: [0, 65535],
  int32: [-2147483648, 2147483647], uint32: [0, 4294967295],
  int64: [-MAX_SAFE, MAX_SAFE], uint64: [0, MAX_SAFE], int: [-MAX_SAFE, MAX_SAFE], uint: [0, MAX_SAFE],
};
const quote = JSON.stringify;
const sha256 = (text) => createHash("sha256").update(text).digest("hex");
const identifier = (name) => `${name[0].toLowerCase()}${name.slice(1).replace(/[^A-Za-z0-9_]/g, "_")}Schema`;
// Names and doc comments do not change a shape.
function shape(schema) {
  const copy = { ...schema };
  for (const key of ["$schema", "title", "description", "definitions"]) delete copy[key];
  return copy;
}

function header(body) {
  return `// Generated by ${generatorVersion} from Rust (schemars 0.8.22); do not edit.\n// Regenerate: npm --prefix web run generate --workspace @print-partner/rust-client\n// Content SHA256: ${sha256(body)}\n${body}`;
}

/** Returns {path: text} for every file in the package's src directory. */
export function generate(document) {
  assert.equal(document.generator, generatorVersion);
  assert.equal(document.schemars, "0.8.22");
  assert.equal(document.dialect, "http://json-schema.org/draft-07/schema#");
  const named = new Map();
  function declare(name, schema) {
    const known = named.get(name);
    if (known) assert.deepEqual(known, schema, `Rust schema name ${name} names two different shapes`);
    else named.set(name, schema);
  }
  for (const [name, root] of Object.entries(document.dtos)) {
    assert.equal(root.$schema, document.dialect, `Unsupported dialect for ${name}`);
    for (const [key, definition] of Object.entries(root.definitions ?? {})) declare(key, shape(definition));
  }
  // A DTO shares its const with an identical definition of the same name.
  for (const [name, root] of Object.entries(document.dtos)) declare(name, shape(root));
  const emitted = new Map();
  const lines = [];
  function reference(name, visiting) {
    if (!emitted.has(name)) {
      assert(!visiting.includes(name), `Recursive Rust schema ${name} is unsupported`);
      assert(named.has(name), `Missing Rust schema definition ${name}`);
      const code = emit(named.get(name), [...visiting, name]);
      emitted.set(name, identifier(name));
      lines.push(`const ${identifier(name)} = ${code};`);
    }
    return emitted.get(name);
  }
  function emit(schema, visiting) {
    assert(schema && typeof schema === "object" && !Array.isArray(schema), "Unsupported boolean schema");
    for (const key of Object.keys(schema)) assert(keywords.has(key), `Unsupported Rust schema keyword ${key}`);
    if (schema.$ref) {
      assert(schema.$ref.startsWith("#/definitions/"), "External schema reference forbidden");
      return reference(schema.$ref.slice(14), visiting);
    }
    // A unit enum with doc comments on its variants: one string per branch.
    if (schema.oneOf?.every(isStringLiteral)) return emit({ type: "string", enum: schema.oneOf.map((branch) => branch.enum[0]) }, visiting);
    if (schema.oneOf) return discriminated(schema.oneOf, visiting);
    if (schema.anyOf) return nullableUnion(schema.anyOf, visiting);
    if (Array.isArray(schema.type)) {
      const types = schema.type.filter((type) => type !== "null");
      assert(types.length === 1 && schema.type.length === 2, "Unsupported multi-type schema");
      return `${emit({ ...schema, type: types[0] }, visiting)}.nullable()`;
    }
    if (schema.enum) {
      assert(schema.enum.length > 0 && schema.enum.every((value) => typeof value === "string"), "Unsupported enum literal");
      return schema.enum.length === 1 ? `z.literal(${quote(schema.enum[0])})` : `z.enum([${schema.enum.map(quote).join(", ")}])`;
    }
    assert(schema.format === undefined || schema.type === "integer", `Unsupported ${schema.type} format ${schema.format}`);
    const emitter = emitters[schema.type];
    assert(emitter, `Unsupported Rust schema type ${schema.type}`);
    return emitter(schema, visiting);
  }
  function nullableUnion(anyOf, visiting) {
    const branches = anyOf.filter((branch) => branch.type !== "null");
    const code = branches.length === 1 ? emit(branches[0], visiting) : `z.union([${branches.map((branch) => emit(branch, visiting)).join(", ")}])`;
    return branches.length < anyOf.length ? `${code}.nullable()` : code;
  }
  const emitters = {
    object(schema, visiting) {
      // A Rust map (BTreeMap<String, T>, serde_json::Map) has no named properties.
      if (schema.additionalProperties !== undefined && schema.additionalProperties !== false) {
        assert(schema.properties === undefined && schema.required === undefined, "Object passthrough/catchall unsupported");
        const values = schema.additionalProperties === true ? "z.json()" : emit(schema.additionalProperties, visiting);
        return `z.record(z.string(), ${values})`;
      }
      const required = new Set(schema.required ?? []);
      for (const key of required) assert(key in (schema.properties ?? {}), `Required property ${key} has no schema`);
      const fields = Object.entries(schema.properties ?? {}).map(([key, value]) => {
        // A serde default only makes the key omittable; the value itself is checked as usual.
        const { default: fallback, ...field } = value;
        assert(fallback === undefined || !required.has(key), "Defaults are unsupported on required properties");
        return `${quote(key)}: ${emit(field, visiting)}${required.has(key) ? "" : ".optional()"}`;
      });
      // deny_unknown_fields rejects unknown keys; other objects strip them.
      return `z.${schema.additionalProperties === false ? "strictObject" : "object"}({${fields.join(", ")}})`;
    },
    array(schema, visiting) {
      assert(schema.items && !Array.isArray(schema.items), "Tuple or untyped array unsupported");
      const min = schema.minItems === undefined ? "" : `.min(${schema.minItems})`;
      const max = schema.maxItems === undefined ? "" : `.max(${schema.maxItems})`;
      return `z.array(${emit(schema.items, visiting)})${min}${max}`;
    },
    integer(schema) {
      let [minimum, maximum] = [schema.minimum, schema.maximum];
      if (schema.format !== undefined) {
        assert(schema.format in integerFormats, `Unsupported integer format ${schema.format}`);
        const [low, high] = integerFormats[schema.format];
        minimum = Math.max(minimum ?? low, low);
        maximum = Math.min(maximum ?? high, high);
      }
      assert(Number.isSafeInteger(minimum) && Number.isSafeInteger(maximum), "Integer bounds must be explicit and within the JavaScript safe range");
      return `z.number().int().min(${minimum}).max(${maximum})`;
    },
    string(schema) {
      let code = schema.pattern ? `z.string().regex(new RegExp(${quote(schema.pattern)}))` : "z.string()";
      // WireText counts Unicode scalar values, as Rust's chars() does, so a
      // length bound comes with x-unicode-scalar and no lone surrogate passes.
      if (schema.minLength === undefined && schema.maxLength === undefined) return code;
      assert(schema["x-unicode-scalar"] === true, "A string length bound needs x-unicode-scalar");
      const min = schema.minLength ?? 0;
      const max = schema.maxLength ?? Number.MAX_SAFE_INTEGER;
      return `${code}.refine((value) => !/[\\uD800-\\uDFFF]/u.test(value) && [...value].length >= ${min} && [...value].length <= ${max})`;
    },
    boolean: () => "z.boolean()",
    null: () => "z.null()",
  };
  function discriminated(branches, visiting) {
    const keys = Object.keys(branches[0].properties ?? {}).filter((key) => branches.every((branch) => branch.properties?.[key]?.enum?.length === 1 && branch.required?.includes(key)));
    assert.equal(keys.length, 1, "Unsupported oneOf without exactly one tag property");
    const values = branches.map((branch) => branch.properties[keys[0]].enum[0]);
    assert.equal(new Set(values).size, values.length, "Unsupported overlapping oneOf");
    return `z.discriminatedUnion(${quote(keys[0])}, [${branches.map((branch) => emit(branch, visiting)).join(", ")}])`;
  }
  const dtoNames = Object.keys(document.dtos).sort();
  for (const name of dtoNames) reference(name, []);
  const schemas = `import { z } from "zod";\n\n${lines.join("\n")}\n\n${dtoNames.map((name) => `export { ${identifier(name)} };\nexport type ${name} = z.output<typeof ${identifier(name)}>;`).join("\n")}\n\n/** Every covered DTO schema by its Rust contract name. */\nexport const dtoSchemas = {${dtoNames.map((name) => `${name}: ${identifier(name)}`).join(", ")}} as const;\n`;
  const routeNames = new Set();
  const routeLines = document.routes.map((route) => {
    assert(/^[a-z][A-Za-z]+$/.test(route.name) && !routeNames.has(route.name), `Invalid route name ${route.name}`);
    routeNames.add(route.name);
    assert(["GET", "POST", "PATCH", "PUT", "DELETE"].includes(route.method), `Unsupported method ${route.method}`);
    assert(["none", "credential"].includes(route.auth), `Unsupported auth ${route.auth}`);
    for (const dto of [route.request, route.response].filter(Boolean)) assert(dtoNames.includes(dto), `Route ${route.name} names unknown DTO ${dto}`);
    const params = [...route.path.matchAll(/\{([a-z_]+)\}/g)].map((match) => match[1]);
    const textParams = route.text_params ?? [];
    for (const param of textParams) assert(params.includes(param), `Route ${route.name} names unknown text parameter ${param}`);
    const headers = route.headers ?? [];
    for (const name of headers) assert(/^[A-Za-z][A-Za-z-]*$/.test(name), `Route ${route.name} names invalid header ${name}`);
    return `  ${route.name}: {method: ${quote(route.method)}, path: ${quote(route.path)}, params: ${quote(params)}, textParams: ${quote(textParams)}, headers: ${quote(headers)}, auth: ${quote(route.auth)}, request: ${route.request ? `dto.${identifier(route.request)}` : "null"}, response: dto.${identifier(route.response)}},`;
  });
  const routes = `import type { z } from "zod";
import * as dto from "./schemas.generated.js";

/** Routes registered in pp-api, from pp_api::client_contract::CLIENT_ROUTES. */
export const routes = {
${routeLines.join("\n")}
} as const;

export type RouteName = keyof typeof routes;
type Route<N extends RouteName> = (typeof routes)[N];
export type RouteParams<N extends RouteName> = {
  [K in Route<N>["params"][number]]: K extends Route<N>["textParams"][number] ? string : number;
};
export type RouteRequest<N extends RouteName> = Route<N>["request"] extends z.ZodType ? z.input<Route<N>["request"]> : never;
export type RouteResponse<N extends RouteName> = z.output<Route<N>["response"]>;

/** Fills a route's path parameters: positive safe-integer IDs, or encoded non-empty strings for text parameters. */
export function routePath<N extends RouteName>(name: N, params: RouteParams<N>): string {
  const values: Record<string, number | string> = params;
  const textParams: readonly string[] = routes[name].textParams;
  return routes[name].path.replace(/\\{([a-z_]+)\\}/g, (_, key: string) => {
    const value = values[key];
    if (textParams.includes(key)) {
      if (typeof value !== "string" || value === "") throw new RangeError(\`\${key} must be a non-empty string\`);
      return encodeURIComponent(value);
    }
    if (typeof value !== "number" || !Number.isSafeInteger(value) || value < 1) throw new RangeError(\`\${key} must be a positive safe integer\`);
    return String(value);
  });
}
`;
  const descriptors = descriptorTables(document, named, dtoNames);
  const index = `export * from "./descriptors.generated.js";\nexport * from "./routes.generated.js";\nexport * from "./schemas.generated.js";\n`;
  return { "descriptors.generated.ts": header(descriptors), "index.ts": header(index), "routes.generated.ts": header(routes), "schemas.generated.ts": header(schemas) };
}

const isStringLiteral = (branch) => branch.type === "string" && branch.enum?.length === 1 && typeof branch.enum[0] === "string" && Object.keys(branch).every((key) => ["type", "enum", "description"].includes(key));

/** The string literals a schema allows, following one local reference. */
function enumValues(schema, named) {
  const resolved = schema.$ref ? named.get(schema.$ref.slice(14)) : schema;
  if (resolved?.oneOf?.every(isStringLiteral)) return resolved.oneOf.map((branch) => branch.enum[0]);
  assert(Array.isArray(resolved?.enum) && resolved.enum.every((value) => typeof value === "string"), "Descriptor key must be a string enum");
  return resolved.enum;
}

/**
 * Emits each entry of the document's `descriptors` list as a record keyed
 * by its key field. Rows must cover the key's Rust enum exactly, in order, and
 * `satisfies Record<...>` makes TypeScript refuse a missing or extra key.
 */
function descriptorTables(document, named, dtoNames) {
  assert(Array.isArray(document.descriptors), "Missing descriptor tables");
  const tables = document.descriptors.map((table) => {
    assert(/^[a-z][A-Za-z]+$/.test(table.name), `Invalid descriptor table name ${table.name}`);
    assert(dtoNames.includes(table.dto), `Descriptor table ${table.name} names unknown DTO ${table.dto}`);
    const keySchema = named.get(table.dto).properties?.[table.key];
    assert(keySchema && named.get(table.dto).required?.includes(table.key), `Descriptor table ${table.name} has no required key ${table.key}`);
    const keys = table.values.map((row) => row[table.key]);
    assert.deepEqual(keys, enumValues(keySchema, named), `Descriptor table ${table.name} must list every ${table.dto}.${table.key} value once, in Rust order`);
    const rows = table.values.map((row) => `  ${quote(row[table.key])}: ${JSON.stringify(row)},`);
    return `/** Rows of ${table.dto}, keyed by \`${table.key}\`, from pp_api::client_contract. */
export const ${table.name} = {
${rows.join("\n")}
} as const satisfies Record<dto.${table.dto}[${quote(table.key)}], dto.${table.dto}>;`;
  });
  return `import type * as dto from "./schemas.generated.js";\n\n${tables.join("\n\n")}\n`;
}

/** Fails unless `directory` holds exactly the generated files with intact content hashes. */
export function verifyIntegrity(directory = packageSource) {
  const names = readdirSync(directory).sort();
  assert.deepEqual(names, ["descriptors.generated.ts", "index.ts", "routes.generated.ts", "schemas.generated.ts"], "rust-client src must hold only generated files");
  for (const name of names) {
    const text = readFileSync(join(directory, name), "utf8");
    const match = /^(?:\/\/ .*\n){2}\/\/ Content SHA256: ([a-f0-9]{64})\n/.exec(text);
    assert(match, `${name}: missing generated header`);
    assert.equal(sha256(text.slice(match[0].length)), match[1], `${name}: hand edit detected; run generate`);
  }
}

/** Fails unless `directory` matches `files` exactly. Never writes. */
export function compare(files, directory = packageSource) {
  verifyIntegrity(directory);
  for (const [name, text] of Object.entries(files)) assert.equal(readFileSync(join(directory, name), "utf8"), text, `${name}: drift from Rust; run generate`);
}

/** Runs pp-api's exporter into a fresh temporary directory and returns the document path. */
export function exportDocument() {
  const directory = mkdtempSync(join(tmpdir(), "pp-rust-client-"));
  const path = join(directory, "document.json");
  const result = spawnSync(process.env.CARGO ?? "cargo", ["run", "--quiet", "--locked", "--manifest-path", "rust/Cargo.toml", "-p", "pp-api", "--features", "codegen", "--bin", "export-rust-client", "--", path], { cwd: repo, stdio: ["ignore", "inherit", "inherit"] });
  assert.equal(result.status, 0, "Rust client contract export failed");
  return path;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  assert(["--write", "--check", "--verify"].includes(mode), "Usage: client.mjs --write|--check|--verify");
  if (mode === "--verify") {
    verifyIntegrity();
  } else {
    const documentPath = exportDocument();
    try {
      const files = generate(JSON.parse(readFileSync(documentPath, "utf8")));
      if (mode === "--write") {
        mkdirSync(packageSource, { recursive: true });
        for (const [name, text] of Object.entries(files)) writeFileSync(join(packageSource, name), text);
        verifyIntegrity();
      } else {
        compare(files);
        const test = spawnSync(process.execPath, ["--conditions=development", "--import", "tsx", "--test", "scripts/rust-contracts/client.test.mjs"], { cwd: join(repo, "web"), stdio: "inherit", env: { ...process.env, PP_RUST_CLIENT_DOCUMENT: documentPath } });
        assert.equal(test.status, 0, "Rust client round-trip tests failed");
      }
    } finally {
      rmSync(join(documentPath, ".."), { recursive: true, force: true });
    }
  }
  console.log(`PASS: rust-client ${mode}`);
}
